allow_rows=""
allow_paths=""
if [ -f "$ALLOWLIST" ]; then
  n=0
  while IFS= read -r raw || [ -n "$raw" ]; do
    n=$((n + 1))
    raw="${raw%$'\r'}"                    # CRLF — เหตุผลเดียวกับตัวดึงพาธข้างล่าง
    raw="${raw#"${raw%%[![:space:]]*}"}"  # ตัดช่องว่างนำหน้า: แถวที่ย่อหน้ามาเคย **หายเงียบ**
                                          # (พาธกลายเป็นสตริงว่าง แล้วถูก `continue` ข้ามไป
                                          #  ก่อนถึงด่าน `# task NNN` ⇒ คนเขียนไม่รู้เลยว่าแถวตัวเองตาย)
    case "$raw" in ''|'#'*) continue ;; esac
    p="${raw%%[[:space:]]*}"              # พาธ = ทุกอย่างก่อนช่องว่างแรก
    [ -n "$p" ] || continue
    # เหตุผลที่ต้องมี `# task NNN`: แถวที่ไม่บอกว่ามาจากใบไหน คือแถวที่ไม่มีใครรื้อได้อีก
    # (คนรุ่นถัดไปไม่รู้ว่ามันถูกใส่ไว้เพราะอะไร ⇒ ปลอดภัยไว้ก่อน = อยู่ตลอดกาล = สุสาน)
    case "$raw" in
      *'# task '[0-9][0-9][0-9]*) ;;
      *)
