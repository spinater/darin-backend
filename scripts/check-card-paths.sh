# จะเป็น "พาธที่อยู่ใน allowlist ถูกรายงานว่าเน่า" ซึ่งอ่านไม่ออกเลยว่าทำไม
in_list() { # $1=พาธที่หา · $2=รายการพาธบรรทัดละหนึ่ง
  local want="$1" a found=1
  while IFS= read -r a; do
    [ "$a" = "$want" ] && found=0
  done <<< "$2"
  return "$found"
}

