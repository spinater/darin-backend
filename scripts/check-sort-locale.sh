#!/usr/bin/env bash
# เกตของ **`sort` ที่ไม่ได้บอกว่าเรียงด้วย locale ไหน** (ใบ 304)
#
# ## กติกาข้อเดียวที่ไฟล์นี้บังคับ
#
# ทุกจุดที่ไฟล์เชลล์ของรีโป **เรียกคำสั่ง `sort`** ต้องมีคำนำหน้า `LC_ALL=…` (หรือ `LC_COLLATE=…`)
# ติดมากับคำสั่งนั้น · `sort` เปล่า ๆ แปลว่า "ลำดับแล้วแต่เครื่องที่ยืนอยู่" ซึ่งไม่ใช่คำตอบที่
# ใครตั้งใจเลือก และเป็นทิศที่ **เงียบเสมอ**: ผลที่ผิดหน้าตาเหมือนผลที่ถูกทุกประการ
#
# ## ทำไมต้องมี — วัดแล้ว ไม่ใช่กลัวไว้ก่อน
#
# `sort` ของเครื่องนี้คือ uutils 0.8.0 และใต้ `LANG=en_US.UTF-8` มันให้เครื่องหมายวรรคตอน
# **น้ำหนักการเรียงเป็นศูนย์** — ไม่ใช่แค่ "เรียงคนละลำดับ" · วัดด้วยอินพุตเจ็ดบรรทัด
# (`foo_bar` `foobar` `a-b` `a_b` `ab` api/src/fee api/src/fee/) ซ้ำได้ทุกวัน:
#
#   LC_ALL=C           sort -u  →  **7 บรรทัด** (ครบ)
#   LC_ALL=en_US.UTF-8 sort -u  →  **3 บรรทัด** — `a-b` = `a_b` = `ab` · `foo_bar` = `foobar`
#                                  · api/src/fee = api/src/fee/
#
# ⇒ `sort -u` **ยุบชื่อที่ต่างกันจริง** ทิ้งเงียบ ๆ · และ `sort` ที่ส่งต่อให้ `uniq`/`comm` ซึ่ง
# เทียบแบบ **ไบต์** คือสองฝั่งที่สมมติคนละลำดับกัน (บั๊กที่ใบ 302 เจอที่ `comm` คำต่อคำ)
#
# 🔴 **ที่ปิดคือทิศที่เงียบ ไม่ใช่บั๊กที่กำลังทำงานอยู่** — การกวาดทั้งรีโปวันเปิดใบ 304 พบจุดเรียก
# ที่ยังเปล่าอยู่ 6 จุด และวัดทุกจุดด้วยข้อมูลจริงของวันนั้นแล้ว **ไม่มีคู่ไหนชนกันเลยสักคู่**
# (ชื่อ trigger/constraint 518 → C 415 · en_US 415 · ลิงก์ใบงาน 327 → 136 · 136 · พาธ 2,458
# → 2,458 · 2,458) ⇒ ห้ามอ่านไฟล์นี้ว่า "มีบั๊กอยู่" และห้ามอ่านว่า "ไม่มีอะไรต้องทำ":
# ที่วัดได้คือ *ข้อมูลวันนี้ยังไม่ชนกัน* ไม่ใช่ *โค้ดกันไว้แล้ว* · วันที่ชื่อคู่แรกชนกัน จะไม่มี
# อะไรส่งเสียงเลย มีแต่ตัวเลขที่ลดลงเฉย ๆ — **ซึ่งคือเหตุผลทั้งหมดที่ต้องเป็นเกต ไม่ใช่การแก้หกจุด**
#
# ## ขอบเขต — คัดด้วย **การยกเว้น** ไม่ใช่รายชื่อสกุล (§6 rule 1)
#
# คลัง = `scripts/lib/shell-corpus.sh` ใบเดียวกับที่ `check-shell-source.sh` และ
# `check-path-bytes.sh` ใช้ (ทุกไฟล์ที่ git ถือ → เป็นเชลล์จริงจากนามสกุลหรือ shebang ·
# ไบนารีอ่านจากไบต์) — สองชั้นที่ถือสำเนาคำตัดสินคนละใบคือโรคที่ §4 จดไว้จากใบ 193
# · และ **พิมพ์จำนวนที่กวาดทุกรอบ** เพราะตัวคัดไฟล์ที่เงียบ ๆ ไม่แมตช์อะไรเลยคือความล้มเหลว
# ที่ `check-file-length.sh` แบกไว้ 193 ใบ
#
# ## ฝั่ง JS อยู่นอกขอบเขต **โดยตั้งใจ** (ตรวจแล้วที่ใบ 304 จะได้ไม่มีใครกวาดซ้ำ)
#
# web/src มี `localeCompare` 8 จุด กับ `.sort(` 22 จุด — ทุกจุดเรียงเพื่อ **แสดงผล** และไม่มี
# จุดไหนเอาผลไปเทียบกับชุดที่เรียงแบบไบต์ ⇒ ไม่มีอาการของใบนี้ · ยิ่งกว่านั้น
# `localeCompare(a, b, "th")` **ตั้งใจให้เรียงตามภาษาไทย** ⇒ ใครกวาดมันไปเป็นการเทียบไบต์
# จะกลายเป็นบั๊กคนละใบ (ผู้ใช้เห็นรายการเรียงผิด) ⇒ ห้ามรวมสองเรื่องนี้เข้าด้วยกัน
set -euo pipefail
cd "$(dirname "$0")/.."

. scripts/lib/shell-corpus.sh
rc=$?
if [ "$rc" -ne 0 ]; then
  echo "FAIL: โหลด scripts/lib/shell-corpus.sh ไม่สำเร็จ (rc=$rc) — คลังของรอบนี้ไม่มีความหมาย"
  exit 1
fi

SCAN="scripts/lib/sort-locale-scan.awk"
HDLIB="scripts/lib/heredoc.awk"
MASKLIB="scripts/lib/shell-mask.awk"
if [ ! -r "$SCAN" ] || [ ! -r "$HDLIB" ] || [ ! -r "$MASKLIB" ]; then
  echo "FAIL: ไม่มีตัวอ่าน $SCAN หรือ $HDLIB หรือ $MASKLIB — ด่านนี้ตรวจอะไรไม่ได้เลย"
  echo "      ⇒ รอบนี้ตรวจอะไรไม่ได้เลย ห้ามอ่านว่า 'ไม่มีอะไรผิด'"
  exit 1
fi

fail=0
swept=0
sites=0
declared=0
notcmd=0

# 🔴 **`-z` + `read -r -d ''` ไม่ใช่ของประดับ** (ใบ 314) — `git ls-files` เปล่า ๆ ใส่เครื่องหมาย
# คำพูดให้พาธที่ไม่ใช่ ASCII ⇒ ไฟล์ชื่อไทยหายจากคลังเงียบ ๆ **ก่อน** ตัวนับจะขยับ · คลังกลาง
# จัดการให้แล้ว ผู้เรียกแค่ต้องอ่านแบบ NUL ให้ถูก
while IFS= read -r -d '' f; do
  swept=$((swept + 1))
  # 🔴 **ต้องเก็บผลใส่ตัวแปรก่อน ไม่ใช่ `done < <(awk …)`** — สถานะออกของ process substitution
  # **ไม่ถึงเชลล์แม่** ⇒ awk ที่ตายกลางคัน (ไฟล์ตัวอ่านพัง · syntax error) จะทำให้ลูปได้ศูนย์บรรทัด
  # แล้วด่าน **พิมพ์ OK exit 0** ทั้งที่ไม่ได้ตรวจไฟล์นั้นเลย = เขียวปลอมเงียบ ๆ ซึ่งเป็นโรคที่
  # กลุ่มเกตนี้ทั้งกลุ่มเกิดมาปิด · สำนวนนี้ลอกมาจาก `scripts/check-shell-source.sh` (ใบ 318)
  # ซึ่งเจอกับดักเดียวกันมาก่อน · เคส S ของ selftest ปักไว้ด้วยตัวอ่านที่พังจริง
  if ! out="$(awk -f "$HDLIB" -f "$MASKLIB" -f "$SCAN" "$f" 2>/dev/null)"; then
    echo "FAIL: $f — ตัวอ่าน ($SCAN) ทำงานไม่สำเร็จ ⇒ รอบนี้ตรวจไฟล์นั้นไม่ได้"
    echo "      ⇒ ห้ามอ่านว่า 'ไม่มีอะไรผิด' — ด่านนี้ยังไม่ได้ตอบอะไรเลยเกี่ยวกับไฟล์ใบนั้น"
    exit 1
  fi
  while IFS=$'\t' read -r ln verdict snip; do
    [ -n "${ln:-}" ] || continue
    case "$verdict" in
      NOTCMD)
        notcmd=$((notcmd + 1))
        continue
        ;;
      DECLARED)
        sites=$((sites + 1))
        declared=$((declared + 1))
        continue
        ;;
    esac
    sites=$((sites + 1))
    fail=$((fail + 1))
    echo "FAIL: $f:$ln — \`sort\` ที่ไม่ได้บอกว่าเรียงด้วย locale ไหน"
    echo "      $snip"
    echo "      ⇒ ใต้ \`en_US.UTF-8\` ของเครื่องนี้ วรรคตอนมีน้ำหนักการเรียงเป็น **ศูนย์**"
    echo "        (วัด: \`a-b\` = \`a_b\` = \`ab\` · \`foo_bar\` = \`foobar\`) ⇒ \`-u\` ยุบชื่อที่ต่างกันจริง"
    echo "        และ \`uniq\`/\`comm\` ที่รับต่อเทียบแบบ **ไบต์** = สองฝั่งสมมติคนละลำดับกัน"
    echo "      แก้: \`LC_ALL=C sort …\` (ลำดับไบต์ — คำตอบที่ถูกเกือบทุกจุด)"
    echo "           ถ้ารอบนั้นตั้งใจวัดเรื่อง collation เอง ให้ประกาศออกมาตรง ๆ เช่น \`LC_ALL=\"\$cand\" sort …\`"
  # here-string ไม่ใช่ท่อ ⇒ ลูปรันในเชลล์ปัจจุบัน ⇒ ตัวนับข้างบนไม่หายไปกับ subshell
  # · ไฟล์ที่ไม่มีจุดเรียกเลยได้บรรทัดว่างหนึ่งบรรทัด ซึ่งยาม `[ -n "$ln" ]` ข้างบนกินไปแล้ว
  done <<<"$out"
done < <(shell_corpus)

# ── ยามเลขศูนย์ **สองตัว ไม่ใช่ตัวเดียว** — คนละสาเหตุคนละทางแก้ (รูปเดียวกับ `check-path-bytes.sh`)
if [ "$swept" -eq 0 ]; then
  echo "FAIL: check-sort-locale กวาดไฟล์เชลล์ไม่ได้เลยสักใบ — ตัวคัดไฟล์พัง ไม่ใช่รีโปสะอาด"
  exit 1
fi
# 🔑 `sites = 0` พิสูจน์ **ตัวอ่าน** ไม่ใช่ตัวคัดไฟล์ — ตั้งชื่อตัวแปรใน awk ชนคำสงวนครั้งเดียว
# ตัวอ่านจะคาย 0 บรรทัดพร้อม stderr แล้วด่านนี้เขียวตลอดกาล (เกิดจริงกับใบ 314 ตอนตั้งชื่อ `sub`)
# ⚠️ ราคาที่ประกาศไว้: วันที่คำสั่ง `sort` หายไปจากไฟล์เชลล์ทั้งรีโป ด่านนี้จะแดง — ทางออกวันนั้น
# คือ **ลบเกตทิ้ง** ไม่ใช่ปิดยามตัวนี้ · เลือกทางนี้เพราะเขียวเงียบขณะที่ไม่ได้ตรวจอะไรเลย
# คือโรคที่กลุ่มเกตนี้ทั้งกลุ่มเกิดมาปิด
if [ "$sites" -eq 0 ]; then
  echo "FAIL: กวาดเชลล์ $swept ใบแล้วไม่เจอจุดเรียก \`sort\` สักจุด — ตัวอ่าน ($SCAN) ตายอยู่ ไม่ใช่รีโปสะอาด"
  exit 1
fi

if [ "$fail" -gt 0 ]; then
  echo "check-sort-locale: FAIL — $fail จุด (กวาดเชลล์ $swept ใบ · จุดเรียก \`sort\` $sites จุด · ประกาศ locale แล้ว $declared จุด)"
  exit 1
fi
# ⚠️ `notcmd` คือ **ตัวดัก ไม่ใช่ด่าน** — คำว่า `sort` ในตำแหน่งอาร์กิวเมนต์เติมคำนำหน้าไม่ได้
# ⇒ พิมพ์จำนวนไว้ให้เห็นทุกรอบ วันที่ตัวเลขนี้ขยับคือวันที่มีคนควรไปดูว่ามันคืออะไร
echo "check-sort-locale: OK — กวาดเชลล์ $swept ใบ · จุดเรียก \`sort\` $sites จุด ประกาศ locale ครบทุกจุด · อ้างชื่อนอกตำแหน่งคำสั่ง $notcmd จุด (นอกขอบเขต)"
