#!/usr/bin/env bash
# เกตของ **`.` ที่ไม่มีใครอ่าน rc** (ใบ 239)
#
# ## กติกาข้อเดียวที่ไฟล์นี้บังคับ
#
# ไฟล์เชลล์ที่ **ไม่มี `set -e`** ทุกใบ ที่ `.` (source) ไฟล์ของรีโปเอง **ต้องอ่านสถานะของมัน**
# — `|| …` หรือ `rc=$?` บรรทัดถัดไป หรือ `if ! . …` · ไม่งั้น `.` ที่ล้มจะบ่นลง stderr
# **แล้วรันต่อจนจบ exit 0**
#
# ## ทำไมต้องมี — วัดแล้ว ไม่ใช่กลัวไว้ก่อน
#
# selftest ของเกตต่าง ๆ ใช้ `set -uo pipefail` **โดยจำเป็น** (มี `-e` ไม่ได้ เพราะมันต้องไม่หยุด
# ตอน assertion ล้ม) ⇒ มันคือคลาสที่เปราะกับเรื่องนี้ทั้งคลาส · ตอนใบ 239 เปิด วัดได้ว่า
# ใบเคสที่ **มีอยู่แต่ syntax พังต้นไฟล์** ทำให้:
#   `check-card-paths-selftest`   ผ่าน 70 → **43** แล้วยังพิมพ์ `OK` exit 0
#   `check-counter-test-selftest` ผ่าน 98 → **82** แล้วยังพิมพ์ `OK` exit 0
# ⇒ รอบที่พิสูจน์ได้ 43 จาก 70 ประกาศตัวเองว่าเขียว · ทั้งคู่เป็น stage ของ `verify.sh`
#
# 🔑 **และเหตุผลที่ต้องเป็น *เกต* ไม่ใช่การแก้สามไฟล์**: การแตก selftest เป็นบาร์เรลเกิดสามครั้ง
# ในหกสัปดาห์ (193 · 195 · 237) ⇒ ครั้งที่สี่จะเปิดรูเดิมโดยไม่มีอะไรบอก · การแก้ที่ไม่มีเกตเฝ้า
# คือความจำของคนเขียน ซึ่งหมดอายุพร้อมคอนเท็กซ์ของเขา
#
# ## ขอบเขต — คัดด้วย **การยกเว้น** ไม่ใช่รายชื่อสกุล (§6 rule 1)
#
# เริ่มจากทุกไฟล์ที่ git ถือ แล้วเลือกเฉพาะที่ **เป็นเชลล์จริง ๆ** (นามสกุล `.sh` หรือ shebang
# ที่มีคำว่า `sh`) — ไม่ใช่รายชื่อที่ต้องมีคนเติม · **คำตัดสินนั้นย้ายไปอยู่ที่
# `scripts/lib/shell-corpus.sh` ตั้งแต่ใบ 314** เพราะเกตใบนั้นใช้คลังชุดเดียวกัน และสองชั้นที่
# ถือสำเนาคำตัดสินคนละใบคือโรคที่ §4 จดไว้จากใบ 193 · และ **พิมพ์จำนวนที่กวาดทุกรอบ** เพราะ
# ตัวคัดไฟล์ที่เงียบ ๆ ไม่แมตช์อะไรเลยคือความล้มเหลวที่ `check-file-length.sh` แบกไว้ 193 ใบ
#
# ## ด่านนี้ไม่ได้อ่านไฟล์ดิบอีกแล้ว — มันอ่าน **มุมมองเฉพาะโค้ด** (ใบ 318)
#
# ตั้งแต่ใบ 239 ถึงใบ 315 ด่านนี้ตัดสินด้วย `grep` บนไฟล์ดิบ ⇒ **ไม่รู้จักไวยากรณ์เชลล์** ⇒ วัดบน
# ทรีจริงวันเปิดใบ 318 (คลัง 55 ใบ · ถูกข้ามด้วยตัวกรอง `set -e` 19 ใบ) ได้สองทิศพร้อมกัน:
#
#   · `set -e` ที่เป็น **ข้อมูลใน heredoc** ทำให้ข้ามไฟล์ทั้งใบ **3 ใน 55** — และใบแรกคือ
#     `scripts/tests/check-path-bytes-selftest.sh` ซึ่งเป็น stage ของ `verify.sh` เอง
#     (มันเขียนถูกอยู่แล้ว **โดยบังเอิญ** แต่ไม่มีอะไรเฝ้ามัน ซึ่งคือทั้งเรื่อง)
#   · กลับทิศ: บรรทัด `.` ในเนื้อ heredoc ถูกนับเป็นจุดตรวจของไฟล์ที่ *ถือ* heredoc นั้น
#     ⇒ `check-shell-source-selftest.sh` คาย **3 จุด** ทั้งที่มีคำสั่ง `.` จริงจุดเดียว =
#     **แดงปลอม** ที่ผู้ถูกฟ้องทำตามคำแนะนำของเกตไม่ได้
#
# ⇒ ทุกการอ่านไฟล์ในลูปข้างล่างเดินผ่าน `$VIEW` ซึ่งเป็นไฟล์เดิม **แทนบรรทัดที่เป็นข้อมูลด้วย
# บรรทัดว่าง** ⇒ เลขบรรทัดตรงกับไฟล์จริงทุกบรรทัด · คำตัดสิน "ข้อมูลหรือคำสั่ง" **ยืมมาจากบ้าน
# เดียวกับใบ 314** (`scripts/lib/heredoc.awk`) ไม่ได้เขียนใหม่
set -euo pipefail
cd "$(dirname "$0")/.."

. scripts/lib/shell-corpus.sh

HDLIB="scripts/lib/heredoc.awk"
VIEW="scripts/lib/shell-code-view.awk"
if [ ! -r "$HDLIB" ] || [ ! -r "$VIEW" ]; then
  echo "FAIL: ไม่มีตัวแยกคำ ($HDLIB / $VIEW) — ด่านนี้แยก \`คำสั่ง\` ออกจาก \`ข้อมูลใน heredoc\` ไม่ได้"
  echo "      ⇒ รอบนี้ตรวจอะไรไม่ได้เลย ห้ามอ่านว่า 'ไม่มีอะไรผิด'"
  exit 1
fi

swept=0
checked=0
bad=0
# ไฟล์ที่ตัวรู้จัก heredoc อ่านไม่ออก ⇒ ด่านมองไม่เห็นทั้งไฟล์ · **คนละสาเหตุคนละทางแก้กับ `bad`**
blind=0

# `.` ของ **ไฟล์ในรีโป** เท่านั้น — `. /etc/profile` หรือ `. "$HOME/x"` ไม่ใช่เรื่องของเกตนี้
# (รูปที่จับ: `. path` · `. "path"` · `. "$VAR"` · `. "$VAR/ชื่อ"` โดยขึ้นต้นบรรทัดหรือมีแต่ช่องว่างนำ)
#
# 🔴 **เทียบที่ *ต้นคำสั่ง* ไม่ใช่ "มีสตริงนี้อยู่ที่ไหนก็ได้ในบรรทัด"** (ใบ 315) — รูปเดิมเขียน
# `*' . /'*` ซึ่ง **บังคับให้มีช่องว่างนำหน้าจุด** ⇒ `  . /etc/profile` (ย่อหน้า) ถูกยกเว้นถูกต้อง
# แต่ `. /etc/profile` ที่คอลัมน์ 0 **ถูกฟ้อง** — เจอตอนเขียน selftest ใบแรกของเกตนี้ **ด้วยการวัด
# ไม่ใช่ด้วยการอ่านโค้ด** · นั่นคือแดงปลอมที่ผู้ถูกฟ้องแก้ตามคำแนะนำของเกตไม่ได้เลย (บรรทัดนั้น
# ไม่ได้ source ไฟล์ของรีโป) ซึ่งเป็นทางที่เร็วที่สุดที่จะทำให้คนเรียนรู้ที่จะเดินข้ามเกต
# · ตัวคัดของ `grep` ข้างล่างการันตีอยู่แล้วว่าบรรทัดขึ้นต้นด้วยช่องว่างแล้วตามด้วย `. ` ⇒ ตัด
# ช่องว่างนำทิ้งแล้วเทียบ **พรีฟิกซ์** คือรูปที่ตรงกับเจตนาเป๊ะ · และมันแคบกว่ารูปเดิมในทิศที่
# สำคัญด้วย: สตริง `. /` ที่โผล่กลางบรรทัด (ในสตริง/คอมเมนต์ท้ายบรรทัด) จะพาทั้งบรรทัดออกนอก
# ขอบเขตแบบ **เขียวเงียบ** ซึ่งเป็นทิศที่อันตรายกว่าแดงปลอม
is_repo_source() {
  local t="${1#"${1%%[![:space:]]*}"}"
  case "$t" in
    '. /'*|'. $HOME'*|'. "$HOME'*) return 1 ;;
    *) return 0 ;;
  esac
}

# 🔴 **`-z` + `read -r -d ''` ไม่ใช่ของประดับ** (ใบ 314) — `git ls-files` เปล่า ๆ **ใส่เครื่องหมาย
# คำพูดให้พาธที่ไม่ใช่ ASCII** (`core.quotePath` = true) ได้ `".docs/artifact/\340\270\225…"`
# ⇒ `[ -f "$f" ]` ล้มทุกใบ ⇒ `continue` เงียบ ๆ **ก่อน** `swept` จะขยับ ⇒ ตัวเลขที่พิมพ์ท้ายรอบ
# มองไม่เห็นรูนี้ด้วยตัวมันเอง · วัดในรีโปจริงวันเปิดใบ: **24 ไฟล์ชื่อไทย** หายจากการกวาดทุกใบ
# ที่ใช้สำนวนเปล่า ๆ · ในโปรเจกต์ที่ requirement ทุกใบเป็นภาษาไทย นี่ไม่ใช่ฉากสมมติ
while IFS= read -r -d '' f; do
  swept=$((swept + 1))

  # มุมมองเฉพาะโค้ดของไฟล์นี้ — เนื้อ heredoc ถูกแทนด้วยบรรทัดว่าง **เลขบรรทัดคงเดิม**
  # ⚠️ `if !` ไม่ใช่ของประดับ: ไฟล์นี้ตั้ง `set -e` ⇒ ถ้า awk ล้ม สคริปต์จะตายเงียบด้วยรหัส
  # ของ awk โดยไม่มีใครรู้ว่ารอบนั้นตรวจไฟล์ไหนไม่ได้ (คลาสเดียวกับที่ทั้งด่านนี้เกิดมาปิด)
  if ! view="$(awk -f "$HDLIB" -f "$VIEW" "$f")"; then
    echo "FAIL: $f — ตัวแยกคำอ่านไฟล์นี้ไม่สำเร็จ ⇒ รอบนี้ตรวจไฟล์นั้นไม่ได้"
    exit 1
  fi

  # 🔴 **heredoc ที่ค้างตอนจบไฟล์ = ตัวรู้จักอ่านไฟล์นี้ผิด** ⇒ ทุกบรรทัดหลังบรรทัดเปิดถูกอ่านเป็น
  # ข้อมูล ⇒ ด่านมองไม่เห็นทั้ง `set -e` และ `.` ของไฟล์นี้ · เหตุที่พบบ่อยที่สุดคือบรรทัดที่
  # **ลงท้ายด้วย `<<ป้าย`** อยู่ในคอมเมนต์หรือในสตริง (ตัวรู้จักตัดสินจากรูปบรรทัด ไม่ใช่ไวยากรณ์)
  # ⇒ ต้องดังออกมา **ไม่ใช่เขียวเงียบ** ซึ่งเป็นโรคที่ด่านนี้เกิดมาปิด · รายละเอียดที่หัว `$VIEW`
  if hd_open="$(grep -m1 '^#!!HEREDOC-OPEN' <<<"$view")"; then
    blind=$((blind + 1))
    echo "FAIL: $f:${hd_open#*$'\t'}" | sed 's/\t/ — heredoc ที่เปิดไว้ไม่มีบรรทัดปิดจนจบไฟล์ · ป้าย: /'
    echo "      ⇒ ทุกบรรทัดหลังจากนั้นถูกอ่านเป็น **ข้อมูล** ⇒ รอบนี้ด่านมองไฟล์นี้ไม่เห็นเลย"
    echo "      แก้: ถ้าบรรทัดนั้นเป็นคอมเมนต์หรือสตริง อย่าให้มันลงท้ายด้วย \`<<ป้าย\`"
    echo "      (เช่นเติมเครื่องหมายปิดท้าย หรือย้ายป้ายไปกลางบรรทัด) · ถ้าเป็น heredoc จริง ให้ปิดมัน"
    continue
  fi

  # สคริปต์ที่มี `set -e` ปลอดภัยอยู่แล้ว — `.` ที่ล้มหยุดทั้งสคริปต์
  if grep -qE '^[[:space:]]*set[[:space:]]+-[a-z]*e' <<<"$view"; then
    continue
  fi

  # ทุกบรรทัดที่เป็นคำสั่ง `.` (ไม่ใช่คอมเมนต์ ไม่ใช่ `..`)
  while IFS=: read -r lineno line; do
    [ -n "${lineno:-}" ] || continue
    is_repo_source "$line" || continue
    checked=$((checked + 1))
    # อ่าน rc แบบใดแบบหนึ่ง: `|| …` ท้ายบรรทัด · `if ! . …` · หรือ `rc=$?`/`$?` ในบรรทัดถัดไป
    # 🔴 **การอ่านครั้งนี้ต้องเป็น *ไฟล์ดิบ* ไม่ใช่ `$view` — และรอบแรกเขียนผิด** · เหตุผล:
    # บรรทัด `.` ที่ถูกนับเป็นโค้ดเสมอ ⇒ บรรทัดถัดจากมันเป็นได้แค่ **โค้ด** หรือ **บรรทัดเปิด
    # heredoc** · แต่ `$view` เป่าบรรทัดเปิดทิ้งด้วย (ตามพฤติกรรมของใบ 314 ที่ `$HDLIB` ประกาศไว้)
    # ⇒ `. x.sh` แล้วบรรทัดถัดไปเป็น `rc=$?; cat <<'EOF'` จะได้ **แดงปลอม** ที่ผู้ถูกฟ้องทำตาม
    # คำแนะนำของเกตไม่ได้เลยนอกจากย้าย heredoc · วัดแล้วด้วยฉากจริง ไม่ใช่คิดเอา (แถว S16)
    # ⚠️ และ **ไม่มีทางที่บรรทัดถัดไปจะเป็นเนื้อ heredoc** — ถ้ามี heredoc เปิดค้างอยู่ก่อนหน้า
    # บรรทัด `.` นั้นก็เป็นข้อมูลไปแล้วและไม่ถูกนับตั้งแต่ต้น ⇒ ไฟล์ดิบถูกเสมอที่ตำแหน่งนี้
    next="$(sed -n "$((lineno + 1))p" "$f")"
    case "$line" in
      *'||'*) continue ;;
      # ⚠️ **แขนนี้เข้าไม่ถึงในวันนี้ และการรู้ตัวดีกว่าการเงียบ** (วัดที่ใบ 315) — ตัวคัดของ
      # `grep` ข้างล่างบังคับว่าบรรทัดต้อง **ขึ้นต้น** ด้วย `.` ⇒ `if ! . "$x"; then` ไม่เคยถูก
      # หยิบมาถึงตรงนี้เลยสักครั้ง ⇒ มันเขียวเพราะ **ไม่ถูกมองเห็น** ไม่ใช่เพราะแขนนี้รับไว้
      # (`checked` ก็ไม่ขยับตามไปด้วย ซึ่งคือหลักฐานที่ selftest ปักไว้เป็นเคส) · เก็บแขนไว้
      # เพราะมันกลายเป็นของจริงทันทีที่ตัวคัดกว้างขึ้น — แต่ห้ามเขียนที่ไหนว่ามันกำลังทำงานอยู่
      *'if ! '*) continue ;;
    esac
    case "$next" in
      *'$?'*) continue ;;
    esac
    bad=$((bad + 1))
    echo "FAIL: $f:$lineno — \`.\` ที่ไม่มีใครอ่าน rc ในสคริปต์ที่ไม่มี \`set -e\`"
    echo "      ${line# }"
    echo "      ⇒ ไฟล์ที่ source ล้ม (หาไม่เจอ / syntax พัง) จะบ่นลง stderr แล้ว **รันต่อจนจบ exit 0**"
    echo "      แก้: \`. \"\$x\"\` แล้วบรรทัดถัดไป \`rc=\$?\` + เช็ค · หรือ \`. \"\$x\" || { …; exit 1; }\`"
  # ⚠️ `grep -v` ท้ายท่อก็ **เข้าไม่ถึง** ด้วยเหตุผลเดียวกัน (วัดที่ใบ 315): ตัวแรกบังคับว่าอักขระ
  # แรกที่ไม่ใช่ช่องว่างต้องเป็น `.` ⇒ บรรทัดที่ขึ้นต้นด้วย `#` ไม่มีทางรอดมาถึงตัวที่สอง · ปล่อยไว้
  # เป็นเข็มขัดเส้นที่สอง แต่ **ห้ามนับเป็นด่าน** และห้ามมีแถวความไวผูกกับมัน (แถวที่ถอดแล้ว
  # ไม่มีอะไรเปลี่ยน = แถวที่วัดความว่างเปล่า ซึ่งคือโรคที่ selftest ทั้งใบเปิดมาปิด)
  done < <(grep -nE '^[[:space:]]*\.[[:space:]]+[^.[:space:]]' <<<"$view" | grep -v '^[0-9]*:[[:space:]]*#')
done < <(shell_corpus)

if [ "$swept" -eq 0 ]; then
  echo "FAIL: check-shell-source กวาดไฟล์เชลล์ไม่ได้เลยสักใบ — ตัวคัดไฟล์พัง ไม่ใช่รีโปสะอาด"
  exit 1
fi

if [ "$bad" -gt 0 ] || [ "$blind" -gt 0 ]; then
  echo "check-shell-source: FAIL — $bad จุด · อ่านไฟล์ไม่ออก $blind ใบ (กวาดเชลล์ $swept ใบ · ตรวจ \`.\` $checked จุด)"
  exit 1
fi
echo "check-shell-source: OK — กวาดเชลล์ $swept ใบ · ตรวจ \`.\` ที่ไม่มี \`set -e\` คุ้ม $checked จุด"
