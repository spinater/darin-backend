      if [ "$noop" = 0 ]; then bumped=$((bumped + 1)); fi  # นับหลังยืนยัน · บรรทัดเดียวเพื่อให้ S15 ถอดตรงบล็อก
      ok=$((ok + 1))
      echo "  คืนแล้ว: $p  (สำรองไว้เมื่อ $age)"
