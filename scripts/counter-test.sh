    # · และเป็นพลวัตเดียวกับที่ใบ 187 ชี้ว่าเป็นรากของอุบัติเหตุ: **ด่านที่ปฏิเสธเรื่องที่ปลอดภัย
    # คือด่านที่สอนให้คนข้ามมัน**
    #
