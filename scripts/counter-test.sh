      [ -n "${p:-}" ] || continue
      total=$((total + 1))
      age="$(age_of "$ts")"
      if [ ! -f "$store/$blob" ]; then
        echo "counter-test: FAIL — ไม่มีสำเนาของ $p ในคลังแล้ว ($store/$blob)" >&2
        fail=$((fail + 1)); continue
      fi
      # เทียบ **สำเนา** กับแฮชที่จดตอน save ก่อน — สำเนาที่เน่าหลัง save คือเคสที่การเทียบ
      # แบบเก่า (`cmp` สำเนา↔ไฟล์ หลัง `cp`) มองไม่เห็นเลย เพราะมันเทียบของที่เพิ่งก๊อปมาจากกัน
      if ! verify_sha "$store/$blob" "$sha"; then
