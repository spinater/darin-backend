      fi
      want=0
      if [ "$have_named" = 1 ]; then is_named "$p" && want=1
      elif [ "$safe" = 1 ]; then want=1
      fi
      if [ "$want" = 1 ]; then
        rm -f "$store/$blob"
        dropped=$((dropped + 1))
        echo "  ทิ้งสำเนา: $p  (สำรองไว้เมื่อ $(age_of "$ts") · $state)"
      else
        printf '%s\t%s\t%s\t%s\n' "$p" "$ts" "$sha" "$blob" >> "$keep_tmp"
        kept=$((kept + 1))
        if [ "$safe" = 0 ]; then
          risky=$((risky + 1))
          echo "  ⚠️ ยังไม่ทิ้ง: $p  (สำรองไว้เมื่อ $(age_of "$ts") · $state)"
          echo "       สำเนาอยู่ที่ $store/$blob — ก๊อปเก็บเองได้ก่อนตัดสินใจ"
        fi
      fi
    done < "$manifest"
    mv "$keep_tmp" "$manifest"

    if [ "$kept" = 0 ]; then
      # คลังว่างแล้ว = เก็บให้เรียบร้อยเหมือนขา `restore` ⇒ รอบถัดไป `save` เริ่มใหม่ได้สะอาด
      rm -rf "${store:?}"
      rmdir "$store_root" 2>/dev/null || true
    fi
    echo "counter-test: ทิ้ง $dropped สำเนา · เหลือในคลัง $kept"
    if [ "$risky" -gt 0 ]; then
      echo "counter-test: **ยังไม่ทิ้ง $risky ใบข้างบน** — ทิ้งของพวกนี้ต้องเอ่ยชื่อทีละใบ:" >&2
      echo "              bash scripts/counter-test.sh drop <ไฟล์ที่ต้องการทิ้ง>..." >&2
      echo "              (คืนทั้งหมดแทนด้วย \`restore\` · ดูรายการด้วย \`status\`)" >&2
      exit 1
    fi
    ;;

  status)
    echo "counter-test: สายนี้คือ $lane [$lane_tier] · คลังของสายนี้ = $root/$store"
    if [ ! -d "$store_root" ]; then
      echo "  ไม่มีคลังค้างอยู่เลย"
      exit 0
    fi
    any=0
    for d in "$store_root"/*/; do
      [ -d "$d" ] || continue
      any=1
      d="${d%/}"
      lbl="[สายอื่น]"
      if [ "$d" = "$store" ]; then lbl="[ของสายนี้]"; fi
      o_pid="$(owner_get pid "$d/owner.txt")"
      o_root="$(owner_get root "$d/owner.txt")"
      o_tier="$(owner_get tier "$d/owner.txt")"
      live="ไม่รู้ว่าใครเป็นเจ้าของ (ไม่มี pid)"
      if [ -n "${o_pid:-}" ]; then
        if kill -0 "$o_pid" 2>/dev/null; then live="เจ้าของยังมีชีวิต (pid $o_pid)"
        else live="⚠️ เจ้าของตายแล้ว (pid $o_pid) — ของค้างที่ไม่มีใครมาคืน"; fi
      fi
      echo "  $lbl $d  [${o_tier:-?}] $live"
      if [ -n "${o_root:-}" ] && [ "$o_root" != "$root" ]; then echo "      ⚠️ คนละราก: $o_root"; fi
      if [ -s "$d/manifest.tsv" ]; then
        manifest_ok "$d/manifest.tsv" || echo "      ⚠️ บรรทัดสุดท้ายเขียนค้าง — คลังนี้นับของไม่ได้ (restore จะปฏิเสธ)"
        while IFS=$'\t' read -r p ts _sha blob || [ -n "${p:-}" ]; do
          [ -n "${p:-}" ] || continue
          echo "      $p  (สำรองไว้เมื่อ $(age_of "$ts")) → $d/$blob"
        done < "$d/manifest.tsv"
      else
        # คลังที่มี blob แต่ manifest ว่าง/หาย = สภาพที่ต้องดังที่สุด ไม่ใช่เงียบที่สุด
        echo "      ⚠️ ไม่มี manifest ที่อ่านได้ แต่คลังยังอยู่ — เหลือ $(find "$d" -name '*.blob' 2>/dev/null | wc -l | tr -d ' ') blob กำพร้า"
      fi
    done
    if [ "$any" != 1 ]; then echo "  ไม่มีคลังค้างอยู่เลย"; fi
    ;;

  *) usage ;;
esac
