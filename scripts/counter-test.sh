    # ⚠️ ไม่ใช่ "ต่างจาก HEAD" — สายที่กำลังทำงานมีไฟล์ต่างจาก HEAD เต็มไปหมดตลอดเวลา
    # ⇒ คำเตือนที่ดังทุกครั้งคือคำเตือนที่ถูกปิดหูภายในวันเดียว · เกณฑ์ที่คมคือ **ขยับในหน้าต่าง**
    # (`-newer $window`) เพราะช่วงเวลานั้นควรมีแต่ของที่เราตั้งใจทำพัง
