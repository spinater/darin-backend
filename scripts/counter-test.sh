    #   **เงียบ ๆ ไม่ได้** เพราะจังหวะแรกพิมพ์ออกมาหมดแล้วว่ากำลังทิ้งอะไร
    if [ ! -d "$store" ]; then
      echo "counter-test: ไม่มีคลังของสายนี้ ($store) — ไม่มีอะไรให้ทิ้ง" >&2
