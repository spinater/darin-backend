      # ที่การตรวจอาร์กิวเมนต์ก่อนก๊อปมีไว้กำจัด) และไฟล์ที่เหลือ **ไม่ถูกเก็บและไม่ถูกเอ่ยชื่อ**
      cp -p "$p" "$store/$blob" || {
        rm -f "$store/$blob"
        echo "counter-test: FAIL — สำรอง $p ไม่สำเร็จ (สิทธิ์/ดิสก์เต็ม) — ยังไม่อยู่ในคลัง" >&2
        cpfail=$((cpfail + 1)); continue
      }
      # อ่านสำเนากลับมาเทียบ **ตอนที่ต้นฉบับยังอยู่** — จุดเดียวที่สำเนาเสียยังแก้ได้ทัน
      # (เทียบตอน restore รู้ว่าเสีย แต่ของจริงหายไปแล้ว)
      src_sha="$(sha256_of "$p")"
      if ! verify_sha "$store/$blob" "$src_sha"; then
        rm -f "$store/$blob"
        echo "counter-test: FAIL — สำเนาของ $p เขียนแล้วไม่ตรงต้นฉบับ — ยังไม่อยู่ในคลัง" >&2
        cpfail=$((cpfail + 1)); continue
      fi
      printf '%s\t%s\t%s\t%s\n' "$p" "$(now)" "$src_sha" "$blob" >> "$manifest"
      saved=$((saved + 1))
      echo "  สำรอง: $p"
    done
    # นับของที่ก๊อปจริง ไม่ใช่ `$#` — ตัวเลขที่ไม่ได้วัดคือตัวเลขที่โกหกได้
    if [ "$cpfail" -gt 0 ]; then
      echo "counter-test: สำรอง $saved ไฟล์ · **ล้ม $cpfail** — อย่าทำพังจนกว่าจะ save ครบ" >&2
      exit 1
    fi
    echo "counter-test: สำรอง $saved ไฟล์แล้ว (คลังถือรวม $n) — ทำพังได้เลย · สาย $lane [$lane_tier]"
    ;;

  restore)
    # ── **อาร์กิวเมนต์ที่ `restore` ไม่รับ = exit 2 ไม่ใช่เมินเงียบ ๆ** (ใบ 248)
    # `usage` ประกาศไว้เองว่า `save`/`drop` รับชื่อไฟล์ ส่วน `restore` ไม่รับ — แต่แขนนี้เคยไม่ดู
    # `$#` เลย ⇒ `counter-test.sh restore read.rs` **คืนทุกไฟล์ในคลัง แล้วลบคลังทิ้ง** พร้อมพิมพ์
    # บรรทัดสำเร็จ · เกิดจริงกลางใบ 247: สายที่ถือสำเนาสองใบตั้งใจคืนใบเดียว ผลคืออีกใบถูกคืนไป
    # ด้วยและคลังหายทั้งใบ ⇒ การทดลองถัดไปเดินต่อ **โดยไม่มีสำเนาสำรอง** โดยที่จอบอกว่าสำเร็จ
    #
    # 🔑 คลาสเดียวกับที่ใบ 231 ปิดที่ `task-move.sh` เป๊ะ (แฟลกที่ไม่รู้จักเคยตกไปที่ทางเลือก
    # ตั้งต้นแล้วพิมพ์ `OK`) — และหนักกว่า เพราะผลลัพธ์ของเครื่องมือนี้คือ **ไฟล์ในทรี** ไม่ใช่
