          exit 1
        fi
        named_list="$named_list
$p"
      done
    fi
    is_named() { case "
$named_list
" in *"
$1
"*) return 0 ;; esac
      return 1; }

    dropped=0; kept=0; risky=0
    keep_tmp="$manifest.keep.$$"
    : > "$keep_tmp"
    while IFS=$'\t' read -r p ts sha blob || [ -n "${p:-}" ]; do
      [ -n "${p:-}" ] || continue
      # สภาพของไฟล์ **เทียบกับสำเนา** — คำถามเดียวที่ตัดสินว่าการทิ้งจะทำให้อะไรหายไหม
