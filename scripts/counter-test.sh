      # เท่ากันทั้งเนื้อและเวลา = no-op · เรียงเวลาก่อนแฮช ⇒ ทางที่พบบ่อยไม่ต้องอ่านไฟล์เลย
      noop=0
      if [ -f "$p" ] && [ ! "$p" -nt "$store/$blob" ] && [ ! "$store/$blob" -nt "$p" ] \
         && verify_sha "$p" "$sha"; then
        noop=1
