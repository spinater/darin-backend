      # แล้วพิมพ์บรรทัดสำเร็จ + ลบคลังทิ้ง** = เขียวปลอมที่ใบนี้เกิดมาเพื่อกัน มาทางใหม่ (รีวิวสายค้าน
      # ของใบ 192 วัดเจอ · เคส U เฝ้าไว้) · ตายก่อน `cp` ก็ปลอดภัย: สำเนาใหม่กว่าไฟล์ ⇒ ยังอ่านว่าต้องประทับ
      if [ "$noop" = 0 ]; then
        touch "$store/$blob" || {
          echo "counter-test: FAIL — ขยับเวลาของสำเนา $p ไม่ได้ — ไม่คืนทับ (คืนไปก็ได้เวลาเก่า ⇒" >&2
