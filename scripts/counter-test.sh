      #   ของคำถาม "ถูกแตะหลัง save หรือยัง" ⇒ **ถอด `-p` ตรงนี้ = ถอดเกณฑ์นั้นไปด้วย ไม่มีอะไรทัก**
      # การ์ดเดียวกับฝั่ง restore — หัวไฟล์ประกาศกติกานี้ไว้เอง แล้วรอบแรกของใบ 187
