# ⚠️ ห้ามพิมพ์รายชื่อหมุดลงในไฟล์นี้ — ทุกฉากผลิตจาก `PINS[@]` ที่อ่านมาจากสำเนาเกตเอง

echo "selftest: เคสพฤติกรรม — พฤติกรรมของ check-code-junit.sh วันนี้"

# ── P. ลิสต์หมุดต้องอ่านได้จริง — **มาก่อนทุกเคส** เพราะทุกฉากข้างล่างผลิตจากลิสต์นี้
# ลิสต์ว่าง = ทุกเคสผ่านแบบว่างเปล่าโดยไม่มีอะไรบอก (บทเรียน `swept = 0` ของใบ 193)
new_sandbox
check "P — อ่านหมุดจากไฟล์ข้อมูลของสำเนาได้ ${#PINS[@]} ใบ (ต้อง ≥ 1)" \
  "$([ "${#PINS[@]}" -ge 1 ] && echo 1 || echo 0)" \
  "อ่าน \`scripts/junit-pins.txt\` จากสำเนาไม่ได้เลย ⇒ ทุกเคสข้างล่างวัดอะไรไม่ได้"

# รูปของแต่ละหมุดต้องเป็นพาธไฟล์เทสจริง — ตัวแยกคำที่พังจะคาย `\` หรือ `do` ออกมาแล้วเงียบ
bad_shape=""
for p in "${PINS[@]}"; do
  case "$p" in
    # darin: เทสอยู่ข้าง ๆ โค้ดที่ `lib/` ไม่ใช่ใต้ `tests/` ⇒ ยึด **นามสกุล** ไม่ใช่ไดเรกทอรี
    # (ไดเรกทอรีเป็นรายการที่ต้องมีคนคอยเติมทุกครั้งที่มีบ้านใหม่ — §6 rule 1)
    */*.test.ts|*/*.test.tsx|*/*.test.js|*/*.test.jsx) ;;
    *) bad_shape="$bad_shape $p" ;;
  esac
done
# ⚠️ ข้อความตอนล้ม **ห้ามคายลิสต์ทั้งก้อน** — ตัวแยกคำที่พังคายซอร์สของเกตออกมาได้เป็นร้อย token
# ลงบรรทัดเดียว ซึ่งกลบทุกอย่างที่เหลือใน log ⇒ พิมพ์สามตัวแรกกับจำนวน
