  "$P1 ไม่ได้ถูกรัน (ถูกลบ/เปลี่ยนชื่อ?)"
expect "F — และชั้นที่สองยิงตามด้วย (ไฟล์ยังอยู่จริงแต่ไม่มีเทสทำงาน)" 1 \
  "$P1 มีอยู่จริงแต่ไม่มีเทสไหนทำงาน"

# ── I. รูปลอมของใบ 215: `describe("<หมุด>", …)` ไปเกิดในไฟล์อื่น แล้วลบไฟล์จริงทิ้ง
