  GATE_LC="$COLL_LC"
  junit_open; junit_default_suites "$EXTRA"
  junit_suite "$COLL_A" "$COLL_A" 1 0; junit_suite "$COLL_B" "$COLL_B" 1 0
  junit_close
  expect "Q — ตัดสินถูกใบใต้ locale $COLL_LC และ comm ต้องไม่บ่นบน stderr" 1 \
    "$EXTRA มีอยู่จริงแต่ไม่มีเทสไหนทำงาน" "comm:"
