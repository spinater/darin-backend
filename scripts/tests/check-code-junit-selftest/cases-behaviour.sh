  "$P1 ไม่ได้ถูกรัน (ถูกลบ/เปลี่ยนชื่อ?)"

# ── F. หมุดยังอยู่ในคอร์ปัส แต่ไม่คาย suite ระดับไฟล์ของตัวเอง + describe ปลอมอยู่ในไฟล์อื่น
