# ── E. ไฟล์ของหมุดถูกเปลี่ยนชื่อ `.ts` → `.tsx` โดยหมุดไม่ได้ตามไป
# 🔴 หลักยึด `"\t"` ใน `index($0, s "\t") == 1` คือสิ่งเดียวที่กันไม่ให้ชื่อหมุดกลายเป็น *คำนำหน้า*
