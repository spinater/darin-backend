# ── C. หมุดหายทั้งไฟล์และ junit → ทิศ "ไฟล์หายไป" ของชั้นที่หนึ่ง
# ครึ่งหลัง (ห้ามได้ข้อความของชั้นที่สอง) คือของจริง: ไฟล์ที่ถูกลบไม่ใช่ไฟล์ที่ "มีอยู่จริง"
new_sandbox
