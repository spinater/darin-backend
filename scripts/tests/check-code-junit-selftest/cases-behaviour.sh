  "ตัวแยกคำคายของที่ไม่ใช่พาธออกมา $bad_n ชิ้น (สามชิ้นแรก: $(echo $bad_shape | cut -d" " -f1-3)) ⇒ ฉากจะถูกสร้างจากขยะ"

# ── A. ทรีปกติ → เขียว + บรรทัดกวาดต้องบอกจำนวนที่ **ตรงกับคอร์ปัสจริง** ไม่ใช่แค่ "มีบรรทัด"
new_sandbox
# deny ใบที่สองคือ `comm:` — `run_gate` รวม stderr เข้ามาด้วย ⇒ เสียงที่ `comm` คายตอน input
# ไม่เรียง **ไม่เปลี่ยนคำตัดสิน** ⇒ ถ้าไม่ deny ไว้มันผ่านไปเงียบ ๆ
# ⚠️ **เคสนี้ตรึง *ความเงียบของวันนี้* เท่านั้น — ไม่ใช่ "ฐานที่ให้แถว S4 ยืน"** (วัดในรีวิวใบ 302):
# ถอด `LC_ALL=C` ออกแล้วรันฉาก A ยังได้ `comm:` **ศูนย์บรรทัด** เพราะคลังกับ `.ran` เหมือนกันเป๊ะ
# ⇒ `comm` เดินคู่กันไปโดยไม่ทันเจอความไม่เรียง · ตัวที่ให้ S4 ยืนคือ **ฉาก Q** ซึ่งมีไฟล์ที่ต่างกัน
# จริงจนบังคับให้ `comm` อ่านล่วงหน้า ⇒ อย่าเขียนว่าเคส A เป็นฐานของ S4
expect "A — ทรีปกติเขียว และพิมพ์บรรทัดกวาด ${#ALL[@]} ใบ" 0 \
  "check-code: กวาดไฟล์เทส ${#ALL[@]} ใบ" "check-code: FAIL" "comm:"

# ── B. อ่าน input ไม่ได้ = แดง ห้ามเงียบ (สองทาง: ไฟล์ว่าง กับ ไม่มีไฟล์)
new_sandbox
: > "$SANDBOX/$JUNIT_REL"
