  "$P1 ไม่ได้ถูกรัน (ถูกลบ/เปลี่ยนชื่อ?)" \
  "$P1 มีอยู่จริงแต่ไม่มีเทสไหนทำงาน"

# ── D. หมุดถูกโหลดแต่ skip ทั้งใบ (`tests - skipped == 0`) — รูที่ใบ 101 วัดมาเอง
