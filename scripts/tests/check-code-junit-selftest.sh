#      เพราะมันตรึง *ข้อความที่ถูกใบ* ในฉากที่ไฟล์หายจริง ซึ่ง F ไม่ได้ตอบ
#   J. ไฟล์อยู่ในคอร์ปัสแต่ไม่มีใน junit → FAIL "มีอยู่จริงแต่ไม่มีเทสไหนทำงาน" (ชั้นที่สองล้วน —
#      ตัวแทนเป็นไฟล์ที่ **ไม่ได้อยู่ในหมุด** จึงแยกสองชั้นออกจากกันได้จริง)
#   K. ชุดใน junit ที่ไม่อยู่ในคอร์ปัส   → FAIL "การกวาดมองไม่เห็นไฟล์นี้" (ทิศกลับของใบ 215 —
#      ตัวที่กันไม่ให้รูปชื่อไฟล์ที่ `case` ไม่จับตายเงียบ)
#   L. ไฟล์ถูกลบจาก **worktree** แต่ยังอยู่ใน **index** → **ต้องไม่ได้**ข้อความของ J
#      (`git ls-files -c` ยังคายมันออกมา ⇒ ตัวกรอง `[ -f ]` ของใบ 215 คือสิ่งเดียวที่กันข้อความเท็จ
#      ซึ่งชี้ไปคนละทางกับสาเหตุ)
#   M. junit ที่อ่าน attribute ไม่ครบ    → FAIL "รูปรายงานเปลี่ยน?" (อ่านของที่ต้องตรวจไม่ออก = แดง)
#   O. **คอร์ปัสว่าง** (`web/` หายจากดิสก์ · index ยังถือไว้) → FAIL ที่ **เรียกชื่อตัวคัดไฟล์**
