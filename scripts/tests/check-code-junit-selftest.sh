# ── อ่านหมุดจาก **ไฟล์ข้อมูลของสำเนาเอง** — หัวใจของกติกา §6 rule 1 ในไฟล์นี้
# ตั้งแต่ใบ 298 รายชื่อหมุดอยู่ที่ `scripts/junit-pins.txt` (เดิมเป็นลูป `for suite in` ในเชลล์)
# ⇒ ฉากทั้งหมดผลิตจากไฟล์นั้น **ไม่ใช่รายชื่อที่พิมพ์มือไว้ในไฟล์นี้** — ไม่งั้นมันคือ "รายการที่
# ต้องคอยเติม" (§6 rule 1) ที่จะพังทันทีที่มีคนเพิ่มหมุดใบถัดไป
# · `PIN_WANT[<path>]` เก็บคอลัมน์จำนวนไว้ด้วย ⇒ ฉากสร้าง junit ที่ **ตรงกับหมุดเป๊ะ** ได้เอง
declare -A PIN_WANT
read_pins() { # $1 = พาธไฟล์ข้อมูลหมุดในแซนด์บ็อกซ์
  local line suite rest want
  PINS=()
  PIN_WANT=()
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in ''|'#'*) continue ;; esac
    suite="${line%%	*}"; rest="${line#*	}"; want="${rest%%	*}"
    [ -n "$suite" ] || continue
    PINS+=("$suite")
    PIN_WANT["$suite"]="$want"
  done < "$1"
  ALL=()
  [ "${#PINS[@]}" -gt 0 ] && ALL=("${PINS[@]}")
  ALL+=("$EXTRA")
  return 0
}


junit_open()  { printf '<?xml version="1.0" encoding="UTF-8"?>\n<testsuites name="bun test">\n' > "$SANDBOX/$JUNIT_REL"; }
junit_close() { printf '</testsuites>\n' >> "$SANDBOX/$JUNIT_REL"; }
junit_raw()   { printf '%s\n' "$1" >> "$SANDBOX/$JUNIT_REL"; }
junit_suite() { # $1=name $2=file $3=tests $4=skipped — รูปเดียวกับที่ bun 1.3.14 เขียนออกมา
  printf '<testsuite name="%s" file="%s" tests="%s" assertions="%s" failures="0" skipped="%s" time="0.01">\n</testsuite>\n' \
    "$1" "$2" "$3" "$3" "$4" >> "$SANDBOX/$JUNIT_REL"
}
junit_default_suites() { # $1 (ไม่บังคับ) = ชุดที่ให้ข้ามไป
  local omit="${1:-}" p
  for p in "${ALL[@]}"; do
    [ "$p" = "$omit" ] && continue
    # หมุดได้จำนวนจาก **ไฟล์ข้อมูลของสำเนาเอง** ⇒ ฉากปกติตรงกับหมุดเป๊ะโดยไม่ต้องพิมพ์เลขที่นี่
    # (ใบ 298 — ถ้าพิมพ์เลขที่นี่ มันคือรายการที่ต้องคอยเติมอีกใบ, §6 rule 1)
    junit_suite "$p" "$p" "${PIN_WANT[$p]:-4}" 0
  done
  return 0
}

# ── เลือก locale ที่ **เรียงสลับกับลำดับไบต์จริง** (ใบ 302) — วัดคุณสมบัติ ไม่ใช่เดาจากชื่อ
# ใต้ `C`: `a-c` (0x2D) มาก่อน `a/b` (0x2F) · ใต้ collation ที่ให้วรรคตอนน้ำหนักศูนย์: เทียบ `ab`
# กับ `ac` ⇒ `a/b` มาก่อน ⇒ ถ้า `head -1` ได้ `a/b` แปลว่า locale นั้นสลับลำดับจริง
# 🔑 **ทำแบบนี้แทนการเช็คชื่อ `en_US.UTF-8` ใน `locale -a`** เพราะชื่อที่ `locale -a` พิมพ์
# (เครื่องนี้ = `en_US.utf8`) ไม่ตรงกับชื่อที่ต้องส่งให้ `LC_ALL` เสมอไป ⇒ เช็คชื่อแล้วพลาด
# = ฉากรันใต้ `C` โดยไม่มีใครรู้ ⇒ **แถวความไวคู่ของมันเขียวโดยไม่ได้วัดอะไร** ซึ่งเป็นความผิด
# ที่ใบ 190 ทำในการ์ดตัวเอง · ที่นี่ถามคำถามที่ฉากต้องการตรง ๆ: "สลับลำดับไหม"
pick_collation_locale() {
  local cand
  for cand in en_US.UTF-8 en_US.utf8 C.UTF-8 $(locale -a 2>/dev/null | grep -i 'utf-\?8' | head -5); do
    [ -n "$cand" ] || continue
    if [ "$(printf 'a/b\na-c\n' | LC_ALL="$cand" sort 2>/dev/null | head -1)" = "a/b" ]; then
      printf '%s\n' "$cand"; return 0
    fi
  done
  return 1
}

