# ── ตัวรันเกต: **source เหมือนของจริง ไม่ใช่ `bash`** ⇒ `fail` เดินทางกลับมาทางเดียวกับใน
# `check-code.sh` · `exit 90` แยกกรณี "สำเนาพังจน source ไม่ผ่าน" ออกจาก "เกตตัดสินว่าแดง"
