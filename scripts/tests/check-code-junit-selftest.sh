#   D. หมุดใบหนึ่ง `tests - skipped == 0` → FAIL "ถูกโหลดแต่ไม่มีเทสไหนทำงานจริง" (รู skip ของใบ 101)
#      ⚠️ **เคสนี้เป็นเคส "ข้อความเดียว" ไม่ได้โดยโครงสร้าง** — ไฟล์นั้นอยู่ในคอร์ปัสแต่ไม่อยู่ใน
