#      `deny` ที่นี่จะได้ false red · เคสที่ใส่ `deny` ได้จริงคือ C · J · L
#   E. **ไฟล์ของหมุดถูกเปลี่ยนชื่อ `.ts` → `.tsx` โดยหมุดไม่ได้ตามไป** → ต้อง FAIL "ไม่ได้ถูกรัน"
#      🔴 **นี่คือเงื่อนไขที่แข็งที่สุดของชั้นที่หนึ่งและไม่เคยมีอะไรเฝ้า** — ตัวหาหมุดเทียบด้วย
