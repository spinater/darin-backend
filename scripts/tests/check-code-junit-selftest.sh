#      ตรงนี้ · ส่วนในฉาก I (ไฟล์จริงถูกลบ) มันเป็นแค่ *ตัวกำหนดคุณภาพข้อความ* เพราะแขน
#      `comm -13` ไปแดงแทนด้วยสาเหตุคนละเรื่อง ⇒ **S5 จึงผูกกับ F ไม่ใช่ I**
