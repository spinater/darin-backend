# `GATE_LC` — locale ที่ฉากบังคับให้เกตรันอยู่ใต้ (ใบ 302) · ว่าง = **ใช้ของเครื่อง**
# 🔴 **`LC_ALL=""` ไม่เท่ากับ "ไม่ได้ตั้ง" บน uutils — วัดแล้ว ไม่ใช่คำอ้างจากสเปก** (รีวิวใบ 302):
#     `LC_ALL=""   bash -c 'printf "a/b\na-c\n" | sort | head -1'`  → `a-c`  (เรียงแบบ **ไบต์**)
#     `env -u LC_ALL bash -c '…'`                                   → `a/b`  (เรียงตาม **locale**)
# ⇒ ร่างแรกของไฟล์นี้ส่ง `LC_ALL="$GATE_LC"` ทุกครั้งโดยอ้าง POSIX ⇒ **ทุกฉากยกเว้น Q จะรันเกต
# ใต้ collation แบบ `C`** ขณะที่ของจริง (`check-code.sh`) รันใต้ `LANG=en_US.UTF-8` ⇒ deny `comm:`
# ของเคส A ซึ่งเป็นฐานให้แถว S4 ยืน **จะยิงด้วยเหตุผลเรื่อง locale ไม่ได้อีกเลย**
# · **กับดักตัวเดียวกับที่ใบนี้เปิดมาปิด มาถึงด้วยถนนเส้นที่สาม ในไฟล์ของมันเอง**
# ⇒ แตกกิ่งจริงด้วย `env`: มีค่า = ตั้ง · ว่าง = `env -u LC_ALL` (ถอดออกจริง ๆ)
# · `new_sandbox` ล้างค่านี้ทุกครั้ง ⇒ ฉากหนึ่งบังคับ locale แล้วไม่รั่วไปฉากถัดไป
GATE_LC=""
GATE_OUT=""
run_gate() { # $1 (ไม่บังคับ) = พาธสำเนาเกตที่จะรัน (สัมพัทธ์กับแซนด์บ็อกซ์ หรือสัมบูรณ์)
  local lib="${1:-$GATE_REL}" rc
  local -a lc_arg=(env)
  if [ -n "$GATE_LC" ]; then lc_arg+=("LC_ALL=$GATE_LC"); else lc_arg+=(-u LC_ALL); fi
  GATE_OUT="$(cd "$SANDBOX" && "${lc_arg[@]}" WEB_JUNIT="$JUNIT_REL" RUN_ID="$RUN_ID" GATE_LIB="$lib" bash -c '
      set -uo pipefail
      fail=0
      . "$GATE_LIB"
      rc=$?
      [ "$rc" -eq 0 ] || exit 90
      exit "$fail"' 2>&1)"
  rc=$?
  return "$rc"
}

check() { # $1=ชื่อ $2=0/1 $3=ข้อความตอนไม่ผ่าน
  if [ "$2" -eq 1 ]; then echo "  ok: $1"; pass=$((pass + 1))
  else echo "  FAIL: $1 — $3"; fail=$((fail + 1)); fi
}

# `$5` เป็น deny ใบที่สอง เพราะเคส A ต้อง deny **สองอย่างคนละชนิด**: `check-code: FAIL` (คำตัดสิน)
# และ `comm:` ที่ `sort` คายลง **stderr** — อย่างหลังคือบั๊กที่ใบ 302 มาแก้ ซึ่งวันนี้ *ไม่เปลี่ยน
# คำตัดสิน* ⇒ ถ้าไม่ deny ไว้ มันจะผ่านไปเงียบ ๆ และแถวความไวของใบ 302 จะไม่มีฐานให้ยืน
expect() { # $1=ชื่อเคส $2=exit ที่คาด $3=ข้อความที่ต้องมี $4=ข้อความที่ต้องไม่มี $5=อีกใบที่ต้องไม่มี
  local name="$1" want="$2" msg="${3:-}" deny="${4:-}" deny2="${5:-}" got ok=1 d
  run_gate; got=$?
  if [ "$got" -ne "$want" ]; then
    echo "  FAIL: $name — exit=$got คาด $want"; ok=0
  fi
  if [ -n "$msg" ] && ! grep -qF -- "$msg" <<<"$GATE_OUT"; then
    echo "  FAIL: $name — ไม่พบข้อความ \"$msg\""; ok=0
  fi
  for d in "$deny" "$deny2"; do
    [ -n "$d" ] || continue
    if grep -qF -- "$d" <<<"$GATE_OUT"; then
      echo "  FAIL: $name — เจอข้อความที่ต้องไม่มี \"$d\" (สาเหตุคนละชั้นถูกรายงานปนกัน)"; ok=0
    fi
  done
  if [ "$ok" -eq 1 ]; then echo "  ok: $name"; pass=$((pass + 1))
  else printf '    --- output ---\n%s\n    --------------\n' "$GATE_OUT"; fail=$((fail + 1)); fi
}

