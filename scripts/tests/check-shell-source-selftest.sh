# เกตของ `scripts/check-shell-source.sh` (ใบ 315)
#
# ## ทำไมเกตใบนี้ต้องมีเกตของตัวเอง — และทำไมเพิ่งมามีวันนี้
#
# `check-shell-source.sh` คือ **stage แรก** ของ `verify.sh` และเป็นด่านที่เฝ้า *เงื่อนไขที่ทำให้
# selftest ทุกใบพูดความจริงได้*: สคริปต์ที่ไม่มี `set -e` แล้ว `.` ไฟล์ของรีโปโดยไม่อ่าน `rc`
# จะเดินต่อจนจบ **exit 0 พร้อมแต้มที่น้อยลง** ตอนไฟล์ที่ source เข้ามาพัง (วัดที่ใบ 239:
# `ผ่าน 70 → 43` และ `98 → 82` โดยทั้งคู่ยังพิมพ์ `OK`)
# ⇒ ทั้งกลุ่ม *เกตของเกต* ตั้งอยู่บนด่านใบนี้ · และ **ตัวมันเองไม่เคยมีเทสสักบรรทัดตั้งแต่ใบ 239**
#
# 🔴 **หลักฐานว่านี่ไม่ใช่ความกลัวลอย ๆ**: ใบ 314 เข้าไปแก้ด่านนี้ตรง ๆ (ใส่ `-z` · ย้ายคลังออกเป็น
# `scripts/lib/shell-corpus.sh`) แล้ว **ไม่มีเทสใบไหนแดงได้เลยถ้าแก้ผิด** — การแก้ที่ไม่มีเกตเฝ้า
# คือความจำของคนเขียน ซึ่งหมดอายุพร้อมคอนเท็กซ์ของเขา
#
# 🔑 **และการเขียนเทสก็จ่ายค่าตัวเองคืนทันทีในรอบแรก** — สามอย่างที่ *วัดเจอ* ไม่ใช่ *อ่านเจอ*:
#   1. `. /etc/profile` ที่ **คอลัมน์ 0** ถูกฟ้อง (ตัวกรองเดิมบังคับให้มีช่องว่างนำหน้าจุด) ⇒
#      แดงปลอมที่ผู้ถูกฟ้องทำตามคำแนะนำของเกตไม่ได้ — แก้แล้วในใบนี้ และแถว S6 เฝ้าไว้
#   2. แขน `*'if ! '*` **เข้าไม่ถึง**: ตัวคัดบังคับให้บรรทัดขึ้นต้นด้วย `.` ⇒ `if ! . "$x"` เขียว
#      เพราะ *ไม่ถูกมองเห็น* ไม่ใช่เพราะแขนนั้นรับ ⇒ เคส D3 ปักด้วย **ตัวนับ** ไม่ใช่ด้วยสีเขียว
#   3. ด่านนี้มีตัวนับศูนย์ **ตัวเดียว** (`swept`) ต่างจาก `check-path-bytes.sh` ที่มีสอง —
#      และนั่นถูกแล้ว เพราะ `checked = 0` เป็นโลกที่ถูกกฎหมาย (ทุกไฟล์มี `set -e`) ⇒ ทำให้แดง
#      ไม่ได้ · ที่ทำแทนคือ **ปักตัวเลข `checked` ไว้ในเคส** (เคส A/I) และแถว S10 พิสูจน์ว่า
#      ถ้าตัวคัด `.` ตายเมื่อไร ตัวเลขนั้นคือที่เดียวที่มันโผล่
#
# ## เคส (ดูของจริงที่ `cases-behaviour.sh` — ที่นี่คือสารบัญ)
#
#   A. ฉากสะอาด = เขียว · พิมพ์ **สองตัวเลข** (กวาดกี่ใบ · ตรวจกี่จุด) และทั้งคู่มากกว่า 0
#   B. `.` ที่ไม่มีใครอ่าน rc ในสคริปต์ที่ไม่มี `set -e` = แดง **เรียกชื่อไฟล์และเลขบรรทัด**
#      · พิมพ์บรรทัดที่ผิดซ้ำ · และบอกทางแก้ที่พิมพ์ได้จริง
#   C. สคริปต์ที่มี `set -e` = เขียว (ตัวกรองที่ทำให้ด่านไม่ท่วม · `set -euo pipefail` ด้วย)
#   D. สามรูปที่อ่าน rc: `|| …` (D1) · `rc=$?` บรรทัดถัดไป (D2) · `if ! . …` (D3 — เขียว
#      **และไม่ถูกนับ**) · และ `rc=$?` ที่ห่างออกไปหนึ่งบรรทัด = **แดง** (D4 — กติกาคือ
#      *บรรทัดถัดไป* ไม่ใช่ *ที่ไหนก็ได้*)
#   E. นอกขอบเขต: `. "$HOME/x"` · `. $HOME/x` · `. /etc/profile` ทั้งแบบย่อหน้าและคอลัมน์ 0
#   F. ไฟล์เชลล์ **ชื่อภาษาไทย** ที่ผิดกติกา = ถูกเรียกชื่อ (ของที่ใบ 314 แก้ไว้แล้วไม่มีอะไรเฝ้า
#      — `check-path-bytes.sh` เฝ้าแค่ว่า *มี `-z`* ไม่ได้เฝ้าว่า *ผลลัพธ์ถูก*)
#   G. กติกาคลัง: shebang ที่มีคำว่า `sh` แต่ไม่มีนามสกุล = อยู่ในคลัง · ไฟล์ที่ไม่ใช่เชลล์ =
#      ไม่อยู่ · **ไบนารีอ่านจากไบต์ ไม่ใช่จากนามสกุล** (`.sh` ที่มี NUL ไม่ถูกกวาด)
#   H. คลังว่าง = FAIL ที่ `swept` (บทเรียนใบ 193) — ไม่ใช่ "ไม่มีอะไรผิด"
#   I. หลายจุดผิดพร้อมกัน = นับครบทุกจุดบนบรรทัดสรุป · และ `checked` นับ **เฉพาะจุดในขอบเขต**
#   J. ของที่ `.gitignore` กินอยู่ = นอกขอบเขตสองทิศ · ไฟล์ที่ยังไม่ `git add` = **ยังนับ** (`-o`)
#
#   — สามใบข้างล่างนี้มาจากใบ 318 (`set -e`/`.` ที่เป็น **ข้อมูลในเนื้อ heredoc**) —
#   K. `set -e` ที่อยู่ใน heredoc **เท่านั้น** ต้องไม่ปิดตาด่านทั้งไฟล์ ⇒ `.` จริงที่ไม่อ่าน rc
#      = แดง **เรียกบรรทัดจริง** และ **ไม่เรียกบรรทัดในเนื้อ heredoc**
#   L. `.` ที่อยู่ใน heredoc **เท่านั้น** = เขียว และ `checked` **ไม่ขยับ** (ทิศแดงปลอม ซึ่งเป็น
#      ทิศที่ผู้ถูกฟ้องแก้ตามคำแนะนำของเกตไม่ได้เลย)
#   M. 🔴 **บรรทัดปิดต้องถูกรู้จัก** — โค้ดที่อยู่ *หลัง* ป้ายปิดต้องกลับมาเป็นโค้ด มิฉะนั้น
#      ไฟล์ที่เหลือมืดทั้งใบแบบเงียบ ๆ ซึ่งคือโรคที่ใบ 318 เปิดมาปิด แค่มาทางประตูใหม่
#   N. ตัวแยกคำหาย = แดงด้วยข้อความของตัวเอง (ไม่ใช่ awk บ่นลง stderr แล้วรอบนั้นอ่านว่าเขียว)
#
# ## ตารางความไว (รันทุกรอบ ไม่ใช่ร้อยแก้ว) — อยู่ใน `cases-sensitivity.sh`
#
# **อ่านของจริงจากไฟล์นั้น และอ่านจำนวน assertion จากบรรทัดสุดท้ายที่ selftest พิมพ์เอง ไม่ใช่
# จากที่นี่** — ตารางในร้อยแก้วไม่มีเกตเฝ้า และใบ 277 เขียนผิด 5 ใน 11 แถวมาแล้ว
#
# ⚠️ ไฟล์นี้ตั้ง `set -uo pipefail` **โดยจำเป็น** (มี `-e` ไม่ได้ เพราะต้องไม่หยุดตอน assertion ล้ม)
# ⇒ มันคือคลาสที่ตัวมันเองกำลังเทสอยู่พอดี ⇒ `.` ทุกจุดข้างล่างนี้ **ต้องอ่าน rc** ไม่งั้นได้เกตที่
# ล้มด้วยโรคที่มันเกิดมารักษา (พิสูจน์ด้วย `bash scripts/check-shell-source.sh` บนไฟล์นี้เอง)
set -uo pipefail
cd "$(dirname "$0")/../.."

# **ต่อ PID** ไม่ใช่ชื่อคงที่ — เครื่องนี้รัน `verify.sh` หลายสายขนานเป็นปกติ (§6 rule 6)
SANDBOX=".scratch/shell-source-selftest-$$"
GATE_REL="scripts/check-shell-source.sh"
CORPUS_REL="scripts/lib/shell-corpus.sh"
# ตั้งแต่ใบ 318 ด่านไม่ได้อ่านไฟล์ดิบแล้ว — มันอ่าน **มุมมองเฉพาะโค้ด** ที่สร้างจากสองไฟล์นี้
# ⇒ แซนด์บ็อกซ์ต้องพกไปด้วย มิฉะนั้นยามหน้าด่านจะแดงทุกเคสด้วยเหตุที่ไม่ใช่เรื่องของเคสนั้น
HDLIB_REL="scripts/lib/heredoc.awk"
VIEW_REL="scripts/lib/shell-code-view.awk"
trap 'chmod -R u+rwX "$SANDBOX" 2>/dev/null; rm -rf "$SANDBOX"' EXIT
pass=0
fail=0

check() { # $1=ชื่อ $2=0/1 $3=ข้อความตอนไม่ผ่าน
  if [ "$2" -eq 1 ]; then echo "  ok: $1"; pass=$((pass + 1))
  else echo "  FAIL: $1 — $3"; fail=$((fail + 1)); fi
}

# `< /dev/null` ไม่ใช่ของประดับ: เกตที่ถูก mutate จนเรียกเครื่องมือโดยไม่มีไฟล์ จะไปอ่าน stdin
# ⇒ selftest ค้างทั้งใบแทนที่จะรายงานผล (กับดักที่ selftest ใบพี่เจอมาแล้วจริง)
GATE_OUT=""
run_gate() { GATE_OUT="$(bash "${1:-$SANDBOX/$GATE_REL}" </dev/null 2>&1)"; }

expect() { # $1=ชื่อ $2=exit ที่คาด $3=ข้อความที่ต้องมี $4=ข้อความที่ต้องไม่มี $5=เกตที่จะรัน
  local name="$1" want="$2" msg="${3:-}" deny="${4:-}" gate="${5:-}" got ok=1
  run_gate "$gate"; got=$?
  if [ "$got" -ne "$want" ]; then echo "  FAIL: $name — exit=$got คาด $want"; ok=0; fi
  if [ -n "$msg" ] && ! grep -qF -- "$msg" <<<"$GATE_OUT"; then
    echo "  FAIL: $name — ไม่พบข้อความ \"$msg\""; ok=0
  fi
  if [ -n "$deny" ] && grep -qF -- "$deny" <<<"$GATE_OUT"; then
    echo "  FAIL: $name — เจอข้อความที่ต้องไม่มี \"$deny\" (สาเหตุคนละชั้นถูกรายงานปนกัน)"; ok=0
  fi
  if [ "$ok" -eq 1 ]; then echo "  ok: $name"; pass=$((pass + 1))
  else printf '    --- output ---\n%s\n    --------------\n' "$GATE_OUT"; fail=$((fail + 1)); fi
}

# `sed -i` เปล่า ๆ บน BSD กินอาร์กิวเมนต์ถัดไปเป็น suffix ⇒ ใช้รูปเดียวกับ selftest ใบพี่
sed_i() { sed -i.bak "$@" && rm -f "${@: -1}.bak"; }

# ── แซนด์บ็อกซ์: `scripts/` ทั้งก้อนถูกกันออกจากคลัง ⇒ สิ่งที่เกตกวาดคือ **ฉากล้วน**
# ⇒ ตัวเลขที่ออกมาอ่านได้ตรง ๆ และเคส H (คลังว่าง) ทำได้จริงโดยไม่ต้องลบตัวเกตทิ้ง
new_sandbox() {
  rm -rf "$SANDBOX"
  mkdir -p "$SANDBOX/scripts/lib" "$SANDBOX/tools"
  cp "$GATE_REL" "$SANDBOX/$GATE_REL"
  cp "$CORPUS_REL" "$SANDBOX/$CORPUS_REL"
  cp "$HDLIB_REL" "$SANDBOX/$HDLIB_REL"
  cp "$VIEW_REL" "$SANDBOX/$VIEW_REL"
  scene_clean
  git init -q "$SANDBOX"
  # กันด้วย `.git/info/exclude` ไม่ใช่ `.gitignore` — เคส H ลบไฟล์ที่ git ถือทิ้งทั้งหมด
  # ซึ่งจะพา `.gitignore` ไปด้วย แล้วลากตัวเกตกลับเข้าคลัง (กับดักเดียวกับ selftest ใบ 195)
  printf 'scripts/\n' > "$SANDBOX/.git/info/exclude"
  git -C "$SANDBOX" add -A >/dev/null 2>&1
}

# ฉากพื้นฐาน: ไฟล์เดียว ไม่มี `set -e` · `.` สองจุดที่ **อ่าน rc ครบทั้งคู่** (คนละรูป)
# ⇒ ฉากนี้ต้องให้ `กวาดเชลล์ 1 ใบ · คุ้ม 2 จุด` เสมอ และตัวเลขทั้งสองคือของที่เคส A ปักไว้
#
# 📇 **ข้อห้ามที่เคยอยู่ตรงนี้ถูกยกเลิกที่ใบ 318 และเหตุผลคือของที่ต้องจำ** — ตั้งแต่ใบ 239 ถึง
# ใบ 315 ด่านอ่านไฟล์ดิบทีละบรรทัด ⇒ สองบรรทัดในเนื้อ heredoc ข้างล่างนี้ถูกนับเป็นจุดตรวจของ
# *ไฟล์นี้* ด้วย (วัดแล้ว: ไฟล์นี้เคยคาย **3 จุด** ทั้งที่มีคำสั่ง `.` จริงจุดเดียว) ⇒ ตอนนั้น
# **ห้าม**เขียนฉากที่มี `.` แบบไม่อ่าน rc ลงในไฟล์นี้ ไม่งั้นได้แดงปลอมใส่ตัวเอง · และไฟล์เคส
# ทั้งสองใบรอดมาได้เพราะมี `set -e` อยู่ใน heredoc ของมัน ซึ่งปิดตาด่านทั้งไฟล์ — **ความบังเอิญ
# นั้นเองคือรูของใบ 318** · วันนี้ปิดแล้ว (เคส K/L/M กับแถว S11–S15 เฝ้าไว้) ⇒ ไฟล์นี้คาย **1 จุด**
# ⚠️ แต่ข้อห้ามที่ยัง **ไม่** ถูกยกเลิกคือ: `.` จริง ๆ ในไฟล์นี้ต้องอ่าน rc เสมอ — ดูย่อหน้า
# `set -uo pipefail` ข้างบน · นั่นคือกติกาที่ด่านนี้บังคับ ไม่ใช่ผลข้างเคียงของ heredoc
scene_clean() {
  cat > "$SANDBOX/tools/ok.sh" <<'EOF'
#!/usr/bin/env bash
set -uo pipefail
. scripts/lib/a.sh || { echo "โหลด a ไม่ได้"; exit 1; }
. scripts/lib/b.sh
rc=$?
[ "$rc" -eq 0 ] || exit 1
echo ok
EOF
  chmod +x "$SANDBOX/tools/ok.sh"
}
add_scene() { mkdir -p "$SANDBOX/$(dirname "$1")"; cat > "$SANDBOX/$1"; git -C "$SANDBOX" add -A >/dev/null 2>&1; }
# เหมือน `add_scene` แต่ **ไม่ `git add`** — ใช้พิสูจน์ว่า `-o` ของคลังนับไฟล์ที่ยังไม่ถูก add
add_untracked() { mkdir -p "$SANDBOX/$(dirname "$1")"; cat > "$SANDBOX/$1"; }

CASES_DIR="scripts/tests/check-shell-source-selftest"
for half in cases-behaviour.sh cases-sensitivity.sh; do
  if [ ! -r "$CASES_DIR/$half" ]; then
    echo "FAIL: หาไฟล์เคสไม่เจอ: $CASES_DIR/$half — รอบนี้จะนับเคสไม่ครบโดยไม่มีอะไรบอก"
    exit 1
  fi
  # shellcheck source=/dev/null
  . "$CASES_DIR/$half"
  rc=$?
  if [ "$rc" -ne 0 ]; then
    echo "FAIL: โหลด $CASES_DIR/$half ไม่สำเร็จ (rc=$rc) — เคสในใบนั้นไม่ได้รันครบ"
    exit 1
  fi
done

chmod -R u+rwX "$SANDBOX" 2>/dev/null
rm -rf "$SANDBOX"
echo "check-shell-source-selftest: ผ่าน $pass · ล้ม $fail"
[ "$fail" -eq 0 ] || exit 1
echo "check-shell-source-selftest: OK"
