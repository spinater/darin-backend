HEAD_TREE=""   # ตั้งโดย make_head_tree — ไม่ส่งผ่าน stdout เพราะ `check` ก็พิมพ์ลง stdout
make_head_tree() {
  local h="$SANDBOX-head" rc
  rm -rf "$h"; mkdir -p "$h"
  # `-c commit.gpgsign=false` — gitconfig ของคนรันต้องไม่เปลี่ยนคำตัดสิน (เคส J คำต่อคำ)
  git -C "$SANDBOX" -c commit.gpgsign=false \
    -c user.email=selftest@example.invalid -c user.name=selftest \
    commit -q -m "ย้ายใบ" >/dev/null 2>&1
  rc=$?
  check "[head_tree] commit ของแซนด์บ็อกซ์สำเร็จ" \
    "$([ "$rc" -eq 0 ] && echo 1 || echo 0)" \
    "git commit rc=$rc ⇒ ทรีที่แตกออกมาจะว่าง แล้วเคสที่ใช้มันวัดอะไรไม่ได้เลย"
  git -C "$SANDBOX" archive HEAD 2>/dev/null | tar -x -C "$h" 2>/dev/null
  git init -q "$h"
  git -C "$h" add -Af >/dev/null 2>&1
  # `lib/demo.ts` อยู่ในนี้ด้วยเพราะ **ข้อความประจำเคสของความไว 10 ออกมาจากไฟล์นั้น** —
  # ทรีที่แตกมาไม่ครบแล้วขาด `lib/` จะทำให้เคส Y ผ่านแบบว่างเปล่า (ไม่มีอะไรให้ตรวจ ⇒ OK)
  check "[head_tree] ทรีที่แตกจาก HEAD มีตัวเกตกับไฟล์ที่ต้องตรวจอยู่จริง" \
    "$([ -s "$h/scripts/check-links.sh" ] && [ -s "$h/README.md" ] \
       && [ -s "$h/lib/demo.ts" ] && echo 1 || echo 0)" \
    "แตกไม่สำเร็จ — ในทรีมีแค่: $(ls -A "$h" 2>/dev/null | tr '\n' ' ')"
  HEAD_TREE="$h"
}

check() { # $1=ชื่อเคส $2=0/1 $3=ข้อความตอนไม่ผ่าน
  if [ "$2" -eq 1 ]; then echo "  ok: $1"; pass=$((pass + 1))
  else echo "  FAIL: $1 — $3"; fail=$((fail + 1)); fi
}


