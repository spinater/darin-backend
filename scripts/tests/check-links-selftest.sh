# ทุกแถวเช็คก่อนว่า `sed` แมตช์จริง — แถวที่ sed ไม่โดนอะไรเลยคือแถวที่วัด "ถอดของที่ไม่ได้รัน
# ออกแล้วไม่มีอะไรเปลี่ยน" ซึ่งจริงโดยโครงสร้าง ไม่ใช่การวัด (§7 เขียนกับดักนี้ไว้เอง)
strip() { # $1=ไฟล์ในแซนด์บ็อกซ์ $2=นิพจน์ sed $3=ชื่อแถว
  local f="$SANDBOX/$1" before
  before="$(cat "$f")"
  sed -i.bak "$2" "$f" && rm -f "$f.bak"
  check "[ความไว] $3 — แก้สำเนาได้จริง" \
    "$([ "$before" != "$(cat "$f")" ] && echo 1 || echo 0)" \
    "sed ไม่ตรงกับซอร์สจริง ⇒ แถวนี้วัดอะไรไม่ได้ (แก้ pattern ให้ตรง)"
}

