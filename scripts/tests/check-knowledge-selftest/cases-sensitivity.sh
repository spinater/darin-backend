#!/usr/bin/env bash
# ตารางความไวของ `scripts/tests/check-knowledge-selftest.sh` (ใบ 322)
#
# 🔑 **"exit เปลี่ยน" อย่างเดียวหยาบเกินไป** — ถอดยามบางตัวแล้วแขนอื่นไปแดงแทนด้วยสาเหตุคนละเรื่อง
# คนละทางแก้ ⇒ ตัววัดหลักคือ **ข้อความลายเซ็น** (ต้องมีก่อนถอด · ต้องหายหลังถอด — หรือกลับทิศ
# สำหรับ *ยาม* ซึ่งถอดแล้วข้อความจะ *โผล่*) · exit ประกาศเพิ่มเฉพาะแถวที่อ้างว่าของที่ถอดเป็น
# **ตัวกำหนดคำตัดสิน** ไม่ใช่ตัวกำหนดถ้อยคำ
#
# ⚠️ ทุกแถว **ปฏิเสธการให้คะแนนถ้า `sed` ไม่ได้แก้อะไรเลย** — แถวที่ `sed` ไม่แมตช์คือแถวที่วัด
# ความว่างเปล่า ซึ่งเป็นโรคเดียวกับที่ด่านทั้งใบเปิดมาปิด
#
# ⚠️ **สำเนาที่ถูกกลายพันธุ์อยู่ *ใน* แซนด์บ็อกซ์เสมอ** — เกตทำ `cd "$(dirname "$0")/.."` เอง
# ⇒ สำเนาที่จอดนอกแซนด์บ็อกซ์จะวิ่งใส่ทรีจริง (บทเรียนใบ 277)
#
# ⚠️ ทุกแถวยังยืนยันเพิ่มว่า **ฉากสะอาดยังเขียวหลังถอด** — ซื้อได้แค่ *"`sed` ไม่ได้กว้างจนสคริปต์พัง"*
# ไม่ใช่ข้อพิสูจน์ว่าการถอดคมพอดี (วันนี้ทุกแถวเป็น no-op บนฉากสะอาด ⇒ ยืนยันข้อนี้ล้มไม่ได้ด้วยเหตุอื่น)

echo "── ตารางความไว (รันจริงทุกรอบ) ──"

# $1=ชื่อแถว $2=นิพจน์ sed $3=ฟังก์ชันจัดฉาก $4=ข้อความลายเซ็น
# $5=(ไม่บังคับ) "invert" ถ้าเป็นยามที่ถอดแล้วข้อความจะโผล่ · $6=(ไม่บังคับ) exit ที่คาดหลังถอด
sens() {
  local name="$1" expr="$2" scene="$3" sig="$4" mode="${5:-normal}" want_exit="${6:-}"
  local before after tgt rc_after
  "$scene"
  run_gate
  before="$GATE_OUT"
  tgt="$SANDBOX/$GATE_REL"
  cp "$tgt" "$tgt.orig"
  sed_i "$expr" "$tgt"
  if cmp -s "$tgt" "$tgt.orig"; then
    echo "  FAIL: [ความไว] $name — sed ไม่ได้แก้อะไรเลย ⇒ แถวนี้วัดความว่างเปล่า (ปฏิเสธการให้คะแนน)"
    fail=$((fail + 1)); rm -f "$tgt.orig"; return
  fi
  pass=$((pass + 1)); echo "  ok: [ความไว] $name — sed แก้สำเนาได้จริง"
  run_gate; rc_after=$?
  after="$GATE_OUT"
  if [ "$mode" = "invert" ]; then
    if ! grep -qF -- "$sig" <<<"$before" && grep -qF -- "$sig" <<<"$after"; then
      echo "  ok: [ความไว] $name (ถอดยามแล้วข้อความ \"$sig\" โผล่มา)"; pass=$((pass + 1))
    else
      echo "  FAIL: [ความไว] $name — ถอดยามแล้วข้อความ \"$sig\" ไม่ได้โผล่"
      fail=$((fail + 1)); printf '    --- after ---\n%s\n    -------------\n' "$after"
    fi
  else
    if grep -qF -- "$sig" <<<"$before" && ! grep -qF -- "$sig" <<<"$after"; then
      echo "  ok: [ความไว] $name (ถอดแล้วข้อความ \"$sig\" หายไป)"; pass=$((pass + 1))
    else
      echo "  FAIL: [ความไว] $name — ข้อความ \"$sig\" ไม่ได้หายหลังถอด (ก่อน: มี=$(grep -qF -- "$sig" <<<"$before" && echo y || echo n) · หลัง: มี=$(grep -qF -- "$sig" <<<"$after" && echo y || echo n))"
      fail=$((fail + 1)); printf '    --- after ---\n%s\n    -------------\n' "$after"
    fi
  fi
  if [ -n "$want_exit" ]; then
    if [ "$rc_after" -eq "$want_exit" ]; then
      echo "  ok: [ความไว] $name — exit หลังถอด = $want_exit (ยามนี้กำหนด *คำตัดสิน* ไม่ใช่แค่ถ้อยคำ)"
      pass=$((pass + 1))
    else
      echo "  FAIL: [ความไว] $name — exit หลังถอด = $rc_after คาด $want_exit"; fail=$((fail + 1))
    fi
  fi
  # ฉากสะอาดบนเกตที่ถูกกลายพันธุ์แล้ว (ไม่เรียก new_sandbox ⇒ ไม่คืนสำเนาเดิม)
  build_clean
  run_gate
  if [ $? -eq 0 ]; then echo "  ok: [ความไว] $name — ฉากสะอาดยังเขียวหลังถอด"; pass=$((pass + 1))
  else
    echo "  FAIL: [ความไว] $name — ฉากสะอาดแดงหลังถอด ⇒ sed กว้างจนสคริปต์พัง ไม่ใช่การถอดยาม"
    fail=$((fail + 1)); printf '    --- after ---\n%s\n    -------------\n' "$GATE_OUT"
  fi
  rm -f "$tgt.orig"
}

# S1 — ตัวเทียบรายใบเอง: ถอดแล้วการ์ดที่ไม่มีแถวเงียบสนิท และรอบนั้นกลายเป็นเขียว (เคส B)
sens "S1 ถอดตัวเทียบ 'การ์ดใบนี้มีแถวไหม'" \
  's|\[\[ \$haystack != \*"\$needle"\* \]\]|false|' scene_b "ไม่มีแถวใน" normal 0

# S2 — ยาม `index_state = ok` หน้าตัวเทียบรายใบ: ถอดแล้วรอบที่ *อ่านแผนที่ไม่ได้* จะพ่นคำตัดสิน
#      รายใบใส่การ์ดทั้งคลังด้วยสาเหตุที่ผิด (เคส F) ⇒ ยาม ⇒ วัดแบบกลับทิศ
sens "S2 ถอดยาม index_state=ok หน้าตัวเทียบรายใบ" \
  's|\[ "\$index_state" = ok \] && \[\[|[[|' scene_f "ไม่มีแถวใน" invert

# S3 — การตัด `#anchor` ในตัวสกัด: ถอดแล้วแถวที่เขียนพร้อม anchor กลายเป็นแดงปลอม (เคส E)
#      ทิศนี้คือทิศที่ผู้ถูกฟ้องแก้ตามคำแนะนำของเกตไม่ได้เลย
sens "S3 ถอดการตัด #anchor ในตัวสกัดลิงก์" \
  's|s/#\.\*\$//; ||' scene_e "ไม่มีแถวใน" invert 1

# S4 — ยาม "อ่าน index.md ไม่ได้": ถอดแล้วรอบนั้น **เขียวโดยไม่ได้ตรวจแผนที่เลย** ซึ่งเป็นทิศเงียบ
#
# ⚠️ **แถวนี้ต้องมีฉากของตัวเอง และการวัดเป็นคนบอก ไม่ใช่การอ่านโค้ด**: รุ่นแรกใช้ `scene_f` ซึ่ง
# จงใจมีการ์ดเกินเพดานอยู่ด้วย (เคส F2 ต้องการมันเพื่อพิสูจน์ว่ารอบนั้นเดินต่อจนจบ) ⇒ ถอดยามแล้ว
# exit ยังเป็น 1 เพราะ **แขนเพดานแดงแทน** ⇒ แถวนั้นจะกำลังวัดเพื่อนบ้านของตัวเอง · ฉากนี้จึงมี
# ความแดงเพียงอย่างเดียวคือยามที่กำลังถูกถอด ⇒ ตัวเลข 1 → 0 แปลว่า "เขียวทั้งที่ไม่ได้ตรวจอะไรเลย"
scene_f_plain() {
  new_sandbox; reset_tree
  plain_card "การ์ด ก" | add_card domain/a.md
  rm -f "$SANDBOX/.docs/knowledge/index.md"
}
sens "S4 ถอดยาม 'อ่าน index.md ไม่ได้'" \
  's|= missing \]|= __never ]|' scene_f_plain "อ่าน .docs/knowledge/index.md ไม่ได้" normal 0

# S5 — ยาม "สกัดลิงก์ไม่ได้สักแถว" (ตัวนับที่สอง): ถอดแล้วตัวสกัดที่ตายไม่โผล่ที่ไหนเลย
sens "S5 ถอดยามตัวนับที่สอง (แผนที่ 0 แถว)" \
  's|= empty \]|= __never ]|' scene_d "สกัดลิงก์การ์ดจาก" normal 0

# S6 — ตัวคั่นหัว-ท้ายของ needle: ถอดแล้วแถว `code/voucher.md` ครอบคลุมการ์ด `voucher.md` ฟรี (เคส J)
sens "S6 ถอดตัวคั่นหัว-ท้ายของ needle" \
  's|^  needle=.*|  needle="$rel"|' scene_j "ไม่มีแถวใน" normal 0

# S7 — **คลาสของตัวสกัดลิงก์**: ย้อนกลับเป็น ASCII-only (รูปเดิมก่อนใบ 322 รอบรีวิว) แล้วการ์ดชื่อไทย
#      **ที่มีแถวอยู่แล้ว** โดนฟ้อง ⇒ เกตพิมพ์ทางแก้เป็น *แถวที่มีอยู่แล้ว* = ความแดงที่ไม่มีทางออก
#      ที่ถูกกฎ · เป็น *ยาม* ⇒ วัดแบบกลับทิศ และประกาศ exit เพราะมันพลิก **คำตัดสิน** ไม่ใช่ถ้อยคำ
#      ⚠️ ฉากต้องมีแถว ASCII อยู่ด้วย (`build_clean`) มิฉะนั้นหลังถอดแล้ว `index_rows` = 0 ⇒ แขน
#      "ตัวสกัดพัง" แดงแทนด้วยสาเหตุคนละเรื่อง และแถวนี้จะไปวัดเพื่อนบ้านของตัวเอง (บทเรียนของ S4)
sens "S7 ย้อนคลาสตัวสกัดลิงก์กลับเป็น ASCII-only" \
  's|\[^)\[:space:\]\]|[A-Za-z0-9_./-]|' scene_g2 "ไม่มีแถวใน" invert 1

# S8 — **ตัวกรอง "เฉพาะแถวตาราง" ของตัวสกัด**: ถอดแล้วลิงก์ในร้อยแก้วกลับมานับเป็นแถว
#      ⇒ เคส K เงียบและรอบนั้นเขียว = เขียวโดยไม่ได้ตรวจสิ่งที่ด่านนี้มีไว้ตรวจ
#      (ประกาศ exit ด้วย เพราะตัวกรองนี้พลิก **คำตัดสิน** ไม่ใช่ถ้อยคำ)
sens "S8 ถอดตัวกรอง 'เฉพาะแถวตาราง' ของตัวสกัดลิงก์" \
  's@\^\[\[:space:\]\]\*\\|@.@' scene_k "ไม่มีแถวใน" normal 0
