  # สักใบ (ต่างจาก groove-clinic ที่มี pdf/xlsx/HEIC ของลูกค้า) ⇒ ฉากต้องมีลิสต์ **ของตัวเอง**
  # ไม่งั้น selftest ของด่านจะตายทั้งใบเพราะสภาพที่ถูกต้องของทรี ซึ่งคือเกตที่แดงใส่ความถูกต้อง
  # 🔑 **แต่ยังผลิตฉากจากลิสต์ ไม่ใช่จากชื่อที่พิมพ์มือไว้ในเคส** — พอวันที่รีโปมีแถวจริง
  # ฉากจะสลับมาใช้แถวจริงเองทันที โดยไม่มีใครต้องมาแก้ไฟล์นี้ (§6 rule 1)
  # ⚠️ **และต้องส่งเสียง** — ฉากที่รันบนลิสต์สังเคราะห์ไม่ได้พิสูจน์แถวจริงสักแถว
  if [ "${#KIND_EXT[@]}" -eq 0 ] && [ "${#KIND_PATH[@]}" -eq 0 ]; then
    {
      printf 'pdf\t# ใบ 001 · แถวสังเคราะห์ของ selftest — ลิสต์จริงของรีโปนี้ยังว่าง\n'
      printf 'fixtures/blob.bin\t# ใบ 001 · แถวรูปพาธ (คนละแขนกับแถวนามสกุล)\n'
    } > "$SANDBOX/$KINDS_REL"
    read_kinds "$SANDBOX/$KINDS_REL"
    echo "  note: scripts/binary-kinds.txt ของจริงว่าง ⇒ ฉากใช้ลิสต์สังเคราะห์ (ไม่ได้พิสูจน์แถวจริง)"
  fi
  if [ "${#KIND_EXT[@]}" -eq 0 ] && [ "${#KIND_PATH[@]}" -eq 0 ]; then
    echo "  FAIL: อ่านชนิดจาก $SANDBOX/$KINDS_REL ได้ 0 แถว ⇒ ทุกเคสข้างล่างวัดอะไรไม่ได้"
    fail=$((fail + 1))
    echo "check-text-bytes-selftest: ผ่าน $pass · ล้ม $fail"
    exit 1
  fi
  EXT1="${KIND_EXT[0]}"
  printf 'export const ok = 1;\n' > "$SANDBOX/web/src/clean.ts"
  printf '# บันทึกสะอาด\n' > "$SANDBOX/docs/note.md"
  local e p
  for e in ${KIND_EXT[@]+"${KIND_EXT[@]}"}; do
    make_binary "$SANDBOX/fixtures/sample.$e"
  done
  for p in ${KIND_PATH[@]+"${KIND_PATH[@]}"}; do
    mkdir -p "$SANDBOX/$(dirname "$p")"
    make_binary "$SANDBOX/$p"
  done
  git init -q "$SANDBOX"
  # กันด้วย `.git/info/exclude` ไม่ใช่ `.gitignore` — เคส G ลบไฟล์ที่ git ถือทิ้งทั้งหมด
  # ซึ่งจะพา `.gitignore` ไปด้วย แล้วลากตัวเกตกลับเข้าคลัง (กับดักเดียวกับ selftest ของใบ 195)
  printf 'scripts/\n' > "$SANDBOX/.git/info/exclude"
  git -C "$SANDBOX" add -A >/dev/null 2>&1
}

make_binary() { printf 'GC\000\001\002binary\n' > "$1"; }

# แถวรูป glob ที่ **ต้องไม่** ยกเว้นให้ `$EXT1` ถ้าเกตเทียบเป็นสตริงตรง (เคส P · แถว S8)
# ⚠️ `sed "s/./?/2"` เฉย ๆ ไม่แมตช์อะไรเลยเมื่อนามสกุลยาวตัวอักษรเดียว ⇒ ได้แถวที่ **เท่ากับ**
# นามสกุลจริง ⇒ เคสกลายเป็นการวัดความว่างเปล่าแบบเงียบ (รีวิวใบ 277)
glob_row_for() { # $1 = นามสกุล
  if [ "${#1}" -ge 2 ]; then printf '%s?%s\n' "${1:0:1}" "${1:2}"; else printf '?\n'; fi
}

# ── จัดฉากไฟล์ข้อมูลใหม่ทั้งใบ **พร้อมตัดฉากที่ไม่เกี่ยว** — ฉากที่มีสาเหตุแดงหลายอย่างปนกัน
# ทำให้แถวความไวประกาศ "exit หลังถอด" ไม่ได้เลย (เหลือแต่การวัดถ้อยคำ ซึ่งอ่อนกว่า)
kinds_file_with() { # $1 = เก็บ fixture ของ EXT1 ไว้ไหม (1/0) · $2.. = บรรทัดของไฟล์ข้อมูล
  local keep="$1" p; shift
  rm -f "$SANDBOX"/fixtures/sample.*
  # 🔑 **ต้องเก็บ fixture ของแถวรูป *พาธ* ด้วย** — ไฟล์ข้อมูลกำลังจะถูกเขียนทับด้วยแถวชุดใหม่
  # ⇒ fixture ที่ `new_sandbox` สร้างไว้ให้แถวพาธจะกลายเป็น binary ที่ไม่มีใครประกาศ ⇒ แดงพร้อมกัน
  # หลายจุด · รีวิวใบ 277 วัดไว้: เติมแถวรูปพาธแถวที่เจ็ดใน `binary-kinds.txt` แล้ว selftest แดง 5 จุด
  # ทั้งที่การ์ดอ้างว่า "ชนิดที่เจ็ดไม่ต้องแก้ selftest สักบรรทัด" — ข้ออ้างนั้นเป็นจริงได้ก็ต่อเมื่อบรรทัดนี้มีอยู่
  for p in ${KIND_PATH[@]+"${KIND_PATH[@]}"}; do rm -f "$SANDBOX/$p"; done
  printf '%s\n' "$@" > "$SANDBOX/$KINDS_REL"
  [ "$keep" -eq 1 ] && make_binary "$SANDBOX/fixtures/sample.$EXT1"
  git -C "$SANDBOX" add -A >/dev/null 2>&1
  return 0
}
make_nul_text() { # $1 = พาธ ; $2 = ข้อความก่อน NUL (ไม่ใส่ = ค่าเริ่มต้น)
  printf '%s\000tail\n' "${2:-head}" > "$1"
}

