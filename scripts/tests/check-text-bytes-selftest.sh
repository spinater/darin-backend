# ── อ่านชนิดที่ประกาศไว้ **จากสำเนาเอง** — ฉากทุกฉากผลิตจากลิสต์นี้ ไม่ใช่จากรายชื่อในไฟล์นี้
KIND_EXT=()
KIND_PATH=()
read_kinds() { # $1 = พาธไฟล์ข้อมูล
  local line tok
  KIND_EXT=(); KIND_PATH=()
  [ -f "$1" ] || return 0
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in '' | '#'*) continue ;; esac
    tok="${line%%[[:space:]]#*}"
    tok="${tok%"${tok##*[![:space:]]}"}"
    [ -n "$tok" ] || continue
    case "$tok" in
      */*) KIND_PATH+=("$tok") ;;
      *) KIND_EXT+=("$tok") ;;
    esac
  done < "$1"
}

