# ── Z: `restore` ไม่รับชื่อไฟล์ — ปฏิเสธ **โดยไม่แตะอะไรเลย**
# ⚠️ ครึ่งที่วัดจริงคือสี่บรรทัดล่าง ไม่ใช่ exit code: อาการเดิมคือ "คืนทั้งคลังแล้วลบคลังทิ้ง"
# ซึ่งเป็นผลที่เกิด *ก่อน* จะรู้ว่าถูกหรือผิด ⇒ ด่านที่ปฏิเสธหลังลงมือไปแล้วก็ยัง exit 2 ได้เหมือนกัน
new_sandbox
run l1 save x.txt >/dev/null
run l1 save y.txt >/dev/null
printf 'BROKEN-X\n' > "$SANDBOX/x.txt"
printf 'BROKEN-Y\n' > "$SANDBOX/y.txt"
run l1 restore x.txt
want_exit 2 "Z (restore ที่ได้ชื่อไฟล์มา = ปฏิเสธ ไม่ใช่เมินเงียบ ๆ)"
want_msg "ไม่รับชื่อไฟล์" "Z (ต้องบอกว่าผิดตรงไหน)"
want_msg "drop" "Z (ต้องชี้ทางที่ใช่ — ใบ 188 เพิ่มกริยานี้มาเพื่อกรณีนี้พอดี)"
want_file x.txt "BROKEN-X" "Z (ห้ามคืนใบที่เอ่ยชื่อ — คำสั่งถูกปฏิเสธทั้งคำสั่ง)"
want_file y.txt "BROKEN-Y" "Z (และห้ามคืนใบอื่นด้วย — นี่คืออาการจริงที่ใบ 248 ปิด)"
[ "$(store_files l1)" = 2 ] && ok \
  || bad "Z — คลังถูกแตะทั้งที่คำสั่งถูกปฏิเสธ (อาการเดิม: คืนทั้งคลังแล้วลบทิ้ง)"
run l1 restore
want_exit 0 "Z (restore เปล่า ๆ ยังทำงานตามเดิม — ด่านใหม่ต้องไม่ปิดทางที่ถูก)"
want_file x.txt "ORIG-X" "Z (และคืนของจริงกลับมาครบ)"
want_file y.txt "ORIG-Y" "Z (ทั้งสองใบ — ครึ่งนี้คือสิ่งที่ restore มีไว้ทำ)"
