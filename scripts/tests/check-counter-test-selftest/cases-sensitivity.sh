# ⚠️ **สามแถวนี้ต้องมีครบ ไม่ใช่แถวเดียวสามมุม** — ถอด S15 ได้ "ไม่ประทับเลย" (เขียวปลอม: เกตรอบ
# ถัดไปอ่าน artifact ของรอบที่ทำพัง) · ถอด S16 ได้ "ประทับทุกใบ" (ไม่ผิดความจริง แต่ปลุกคอมไพล์ทั้งชุด
# ฟรีทุกรอบ) · ถอด S17 ได้ "ประทับถูกแต่มีช่องว่างให้ตาย" ⇒ สามสาเหตุ สามวิธีแก้ ⇒ ต้องมีเคสคู่คนละใบ
#
# 🔑 **วัดบนสคริปต์ตัวจริงแล้วทั้งสามแถว (2026-09-01) และผลที่วัดได้แก้ตารางนี้เอง — สองที่**:
# 1. **S15 ไม่ใช่ "R เดี่ยว"** อย่างที่เขียนไว้ก่อนวัด — มันพลิก **U ด้วย** เพราะ R กับ U พึ่งการประทับ
#    อันเดียวกัน · ตัวที่พิสูจน์ว่า **U ไม่ซ้ำซ้อนกับ R** จึงเป็น **S17** ไม่ใช่ S15: ย้าย `touch` ไปหลัง
#    `cp` แล้ว **R/T ยังเขียว แต่ U แดง** ⇒ U เฝ้า *ช่องว่าง* ซึ่งไม่มีเคสอื่นเฝ้า
# 2. บรรทัดสรุป `ประทับเวลาใหม่ N ใบ` เป็น assertion ที่ R กับ T **ใช้ร่วมกัน** (S15 ได้ 0 · S16 ได้ 2)
#    ⇒ แยกสาเหตุไม่ได้ · ตัวที่แยกได้คือ `-nt` รายใบ ⇒ **คำว่า "เดี่ยว" ต้องผูกกับ assertion ไม่ใช่กับเคส**
#    เมื่อเคสหนึ่งมีหลาย assertion — ไม่งั้นวันที่เหลือแต่บรรทัดสรุป ตารางจะอ่านว่า "แดงเหมือนกัน" ทุกสาเหตุ
# · รอบวัดยังยืนยันอีกอย่าง: ถอดการแก้บนสคริปต์ตัวจริงแล้ว `sed_must_match` ของแถวนั้น **แดงเอง**
#   ("sed ไม่แมตช์อะไรเลย") ⇒ ความไวที่วัดไม่ได้ ถูกนับเป็นความล้มเหลว ไม่ใช่ถูกข้ามเงียบ ๆ
#
# 🔑 **บทเรียนที่ทำให้ตารางนี้อ่านออก — ทั้งหมดคือ "เคสที่ผ่านแบบว่างเปล่า" คนละแบบ**
# (เจอสี่รอบในใบเดียว ⇒ นี่คือคลาสที่ต้องไล่ตรวจทุกครั้ง ไม่ใช่ความซวยรายครั้ง):
# · เคส D/I เคยเดาชื่อ blob เป็น `0001.blob` ⇒ แดงพ่วงไปกับ S3/S4 · แก้ด้วย `blob_path` ที่อ่าน manifest
# · S7 เคยถอดแค่ด่าน `-f` ⇒ ด่าน `-r` บรรทัดถัดไปยังกันไว้ ⇒ "sed แมตช์" ≠ "ถอดการแก้ได้จริง"
# · **`setsid` ต้องมี `-w`** — ถ้ามัน fork มันคืน 0 ทันทีโดยไม่รอลูก ⇒ เคส K อ่าน exit code
#   ของ `setsid` ไม่ใช่ของสคริปต์ · และใต้ pty จริงกลายเป็น **แดงปลอม** ⇒ "เกตแดงเมื่อคนพิมพ์เอง
#   เขียวเมื่อ agent พิมพ์" ซึ่งรากคือข้อนี้ ไม่ใช่ `$$`/`$PPID` (คนละใบ วัดแยกที่ S8)
# · เคส P วางยาด้วย **พาธสัมพัทธ์** สองรอบ (ครั้งแรก `ENVIRON[]` ที่ไม่ได้ export · ครั้งที่สอง
#   พาธที่ resolve ผิดชั้นเพราะสคริปต์ `cd` เข้ารากก่อน) ⇒ คำสั่งที่วางยาล้มเอง เคสเลยเขียว
#   **ตัวจับทั้งสองครั้งคือตารางนี้เอง** — ถอดด่านแล้วเคสไม่แดง = เคสที่ไม่มีอยู่จริง
# ══ ความไว: ถอนการแก้ทีละข้อ แล้วเคสคู่ของมันต้องแดง ══════════════════════════════
sens() { # $1=ชื่อเคส S, $2=ผลที่คาด (0=ยังเขียว/1=ต้องแดง), $3=คำอธิบาย
  if [ "$RC" = "$2" ]; then ok; else bad "$1 — exit=$RC คาด $2 ($3)"; fi
}

# S1: ถอดเนื้อใน verify_sha → เคส I ต้องแดง
new_sandbox
if sed_must_match 's|^  \[ "\$(sha256_of "\$1")" = "\$2" \]$|  true|' "S1"; then
  run l1 save x.txt >/dev/null
  printf 'ROTTEN\n' > "$(blob_path l1 x.txt)"
  printf 'BROKEN\n' > "$SANDBOX/x.txt"
  run l1 restore
  sens "S1" 0 "ถอด verify_sha แล้วเคส I ต้องหยุดจับ ⇒ exit 0 ที่นี่คือความไวที่พิสูจน์แล้ว"
  want_file x.txt "ROTTEN" "S1 (พิสูจน์ว่าเนื้อเน่าไหลถึงไฟล์จริงเมื่อถอดการแก้)"
fi

# S2: ด่านรายไฟล์ → กลับเป็น "มีของค้าง = ปฏิเสธ" → เคส B ต้องแดง
new_sandbox
if sed_must_match 's|if is_held "\$p"; then|if [ -s "$manifest" ]; then|' "S2"; then
  run l1 save x.txt >/dev/null
  run l1 save y.txt
  sens "S2" 1 "ถอดด่านรายไฟล์แล้ว save ไฟล์ใหม่ต้องถูกปฏิเสธอีกครั้ง = เคส B แดง"
fi

# S3: เลข blob → กลับเป็น tr '/' '_' → เคส F ต้องแดง
new_sandbox
if sed_must_match "s|blob=\"\$(printf '%04d' \"\$n\").blob\"|blob=\"\$(printf '%s' \"\$p\" \| tr '/' '_')\"|" "S3"; then
  run l1 save a/b.txt a_b.txt >/dev/null
  printf 'BROKEN\n' > "$SANDBOX/a/b.txt"
  printf 'BROKEN\n' > "$SANDBOX/a_b.txt"
  run l1 restore
  # ชนกันแล้ว blob ใบเดียวถูกทับ ⇒ อย่างน้อยหนึ่งใบต้องคืนผิด (แฮชที่จดไว้เป็นตัวจับ)
  sens "S3" 1 "ถอดเลข blob แล้วพาธที่ยุบชนกันต้องคืนผิด = เคส F แดง"
fi

# S4: คลังต่อสาย → path เดียว → เคส E ต้องแดง
new_sandbox
if sed_must_match 's|^store="\$store_root/\$lane"$|store="$store_root"|' "S4"; then
  run laneA save x.txt >/dev/null
  run laneB save y.txt >/dev/null
  printf 'BROKEN\n' > "$SANDBOX/x.txt"
  run laneB restore >/dev/null
  # สาย B ได้คลังเดียวกับ A ⇒ ต้องเห็นอาการอย่างใดอย่างหนึ่ง: คืนไฟล์ของ A ทับ หรือถูก owner กัน
  if [ "$(cat "$SANDBOX/x.txt")" = "ORIG-X" ] || [ "$RC" != 0 ]; then ok
  else bad "S4 — ถอดคลังต่อสายแล้วสองสายยังไม่ชนกัน = เคส E ไม่ได้เฝ้าอะไร"; fi
fi

# S5: รายงาน "สิ่งที่ไม่ได้ทำ" → เคส G ต้องแดง
new_sandbox
if sed_must_match 's|^    if \[ -f "\$window" \]; then$|    if false; then|' "S5"; then
  run l1 save x.txt >/dev/null
  printf 'BROKEN\n' > "$SANDBOX/x.txt"
  printf 'BROKEN\n' > "$SANDBOX/z.txt"
  run l1 restore
  deny_msg "ไม่ได้อยู่ในคลัง: z.txt" "S5 (ถอดบล็อกรายงานแล้วคำเตือนต้องหายไป = เคส G แดง)"
fi

# S6: ตัวกรอง -newer → เหลือ "ต่างจาก HEAD" → เคส H ต้องแดง (ดังใส่งานจริง)
new_sandbox
if sed_must_match 's#^        \[ -n "$(find "$sp" -newer .*$#        :#' "S6"; then
  printf 'REAL-WORK\n' > "$SANDBOX/z.txt"
  sleep 1
  run l1 save x.txt >/dev/null
  printf 'BROKEN\n' > "$SANDBOX/x.txt"
  run l1 restore
  want_msg "ไม่ได้อยู่ในคลัง: z.txt" "S6 (ถอดตัวกรองหน้าต่างแล้วต้องดังใส่งานจริง = เคส H แดง)"
fi

# S7: ตรวจอาร์กิวเมนต์ก่อนก๊อป → เคส J ต้องแดง (เหลือ blob กำพร้า)
new_sandbox
# ต้องถอด **ทั้งสองบรรทัด** ของการตรวจก่อนก๊อป — ถอดแค่ `-f` แล้ว `-r` ยังกันไว้อยู่
# (เจอตอนวัดรอบแรก: S7 ไม่แดง ทั้งที่ sed แมตช์ ⇒ ความไวที่ยังพิสูจน์ไม่ได้ ไม่ใช่ความไวที่ผ่าน)
if sed_must_match 's#^      \[ -f "$p" \] || { echo "counter-test: .*$#      :#; s#^      \[ -r "$p" \] || { echo "counter-test: .*$#      :#' "S7"; then
  run l1 save x.txt no-such-file.txt y.txt
  blobs="$(find "$SANDBOX/.scratch/counter-test" -name '*.blob' 2>/dev/null | wc -l | tr -d ' ')"
  [ "$blobs" != 0 ] && ok || bad "S7 — ถอดการตรวจก่อนก๊อปแล้วยังไม่เหลือ blob กำพร้า = เคส J ไม่ได้เฝ้าอะไร"
fi

# S9: ถอดด่าน manifest ที่เขียนค้าง → เคส M ต้องแดง
new_sandbox
if sed_must_match 's|^manifest_ok() .*$|manifest_ok() { true; }|' "S9"; then
  run l1 save x.txt y.txt >/dev/null
  truncate -s -1 "$(store_dir l1)/manifest.tsv"
  printf 'BROKEN\n' > "$SANDBOX/x.txt"
  printf 'BROKEN\n' > "$SANDBOX/y.txt"
  run l1 restore
  sens_ok=0
  [ "$RC" = 0 ] && sens_ok=1
  case "$OUT" in *"ตรงกับแฮชที่จดตอน save ทุกใบ"*) sens_ok=1 ;; esac
  [ "$sens_ok" = 1 ] && ok || bad "S9 — ถอดด่าน manifest แล้วยังไม่พิมพ์บรรทัดสำเร็จบนการคืนที่ขาด = เคส M ไม่ได้เฝ้าอะไร"
fi

# S8: ชั้น tty ถาม `$PPID` แทน `$$` → เคส K′ ต้องแดง (ต้องมี pty จริงถึงจะแยกออก)
if command -v script >/dev/null 2>&1 && command -v setsid >/dev/null 2>&1; then
  new_sandbox
  if sed_must_match 's|ps -o tty= -p "\$\$"|ps -o tty= -p "$PPID"|' "S8"; then
    OUT="$(script -q -e -c "cd \"$SANDBOX\" && env -u COUNTER_TEST_LANE -u CLAUDE_CODE_SESSION_ID setsid -w bash scripts/counter-test.sh save x.txt" /dev/null 2>&1)"
    RC=$?
    [ "$RC" != 3 ] && ok || bad "S8 — ถอด \$\$ กลับเป็น \$PPID แล้วเคส K′ ยังเขียว = K′ ไม่ได้เฝ้าอะไร"
  fi
else
  echo "  ข้าม S8 (เครื่องนี้ไม่มี script/setsid) — ความไวของ K′ ไม่ได้ถูกวัดในรอบนี้"
fi

# S15: ถอดการประทับเวลาใหม่ตอน restore → เคส R ต้องแดง
new_sandbox
if sed_must_match 's|^      if \[ "\$noop" = 0 \]; then$|      if false; then|' "S15"; then
  run l1 save x.txt >/dev/null
  printf 'BROKEN\n' > "$SANDBOX/x.txt"
  MK="$SANDBOX/.scratch/mark"; touch "$MK"; sleep 1
  run l1 restore
  [ "$SANDBOX/x.txt" -nt "$MK" ] \
    && bad "S15 — ถอดการประทับเวลาแล้ว x.txt ยังใหม่กว่าหมุด = เคส R ไม่ได้เฝ้าอะไร" || ok
fi

# S16: ถอดการตรวจ "การคืนไม่ได้เปลี่ยนอะไร" (= touch ทุกใบเสมอ) → เคส T ต้องแดง
new_sandbox
if sed_must_match 's|^        noop=1$|        noop=0|' "S16"; then
  run l1 save x.txt y.txt >/dev/null
  printf 'BROKEN\n' > "$SANDBOX/x.txt"
  MK="$SANDBOX/.scratch/mark"; touch "$MK"; sleep 1
  run l1 restore
  [ "$SANDBOX/y.txt" -nt "$MK" ] && ok \
