# **บ้านเดียวของคำถาม "ไฟล์ไหนคือไฟล์เชลล์"** (ใบ 314)
#
# ก่อนใบนี้คำตอบนั้นอยู่ในตัว `scripts/check-shell-source.sh` (ใบ 239) ที่เดียว · พอใบ 314 ต้องการ
# คลังชุดเดียวกัน ทางที่ง่ายคือก๊อปลูปไปอีกใบ — ซึ่งคือ **สำเนาที่สองของคำตัดสิน** ที่ §4 ห้ามไว้
# ตรง ๆ จากบทเรียนใบ 193: *"สองชั้นที่บังคับใช้ต้องไม่ถือสำเนาของคำตัดสินคนละใบอีก — ก่อนใบ 193
# มันถืออยู่ และสองสำเนานั้นแค่บังเอิญตรงกัน"*
#
# ## กติกาของคลัง — คัดด้วย **การยกเว้น** ไม่ใช่รายชื่อสกุล (§6 rule 1)
#
# เริ่มจากทุกไฟล์ที่ git ถือ (`-c -o --exclude-standard` ⇒ ไฟล์ใหม่ที่ยังไม่ `git add` ก็นับ ·
# ของที่ `.gitignore` กินอยู่นอกขอบเขต) แล้วเหลือไว้เฉพาะที่ **เป็นเชลล์จริง ๆ**: นามสกุล `.sh`
# หรือ shebang ที่มีคำว่า `sh` · **ไบนารีอ่านจากไบต์** (`grep -Iq .`) ไม่ใช่จากนามสกุล
#
# 🔴 **`-z` ไม่ใช่ของประดับ** (ใบ 314) — `git ls-files` เปล่า ๆ ใส่เครื่องหมายคำพูดให้พาธที่ไม่ใช่
# ASCII (`core.quotePath` = true) ⇒ `[ -f "$f" ]` ล้มทุกใบ ⇒ ไฟล์ชื่อไทยหายจากคลังเงียบ ๆ
# **ก่อน** ตัวนับใด ๆ จะขยับ ⇒ ตัวเลข `กวาด N` ที่พิมพ์ท้ายรอบมองไม่เห็นรูนี้ด้วยตัวมันเอง

# คาย **NUL-separated** — ผู้เรียกต้องอ่านด้วย `read -r -d ''` เสมอ
shell_corpus() {
  local f
  while IFS= read -r -d '' f; do
    [ -f "$f" ] || continue
    grep -Iq . "$f" 2>/dev/null || continue
    case "$f" in
      *.sh) ;;
      *) head -1 "$f" 2>/dev/null | grep -qE '^#!.*\bsh\b' || continue ;;
    esac
    printf '%s\0' "$f"
  done < <(git ls-files -c -o --exclude-standard -z)
}
