# ## ปัญหาที่ไฟล์นี้ปิด (เพดานที่ใบ 150 สร้างขึ้นเองและจดไว้)
# โหมดเนทีฟรัน `cargo` เป็น **ลูกของสคริปต์บนโฮสต์** ไม่ใช่ในคอนเทนเนอร์ ⇒ `kill` ที่ตัวสคริปต์
# (สัญญาณถึง**โพรเซสเดียว** ซึ่งคือวิธีที่ §6 rule 6 สั่งให้ใช้) ทำให้ `cleanup` ทำงานครบ
# คอนเทนเนอร์ถูกลบเรียบร้อย **ดูเหมือนสะอาด** — แต่ `cargo` ยังวิ่งต่อและยังถือ build lock ของ
# api/target ⇒ เกตรอบถัดไปไปนั่งค้างที่ `Blocking waiting for file lock on build directory`
#
# ## ทำไมไม่ใช่ `kill -- -$$` ตามที่ใบ 151 ร่างไว้
# `$$` เป็น **PGID ก็ต่อเมื่อสคริปต์เป็นหัวหน้ากลุ่ม** ซึ่งเป็นจริงเฉพาะตอนถูกเรียกจาก shell
# แบบมี job control · เส้นทางจริงของเกตคือ `verify.sh` เรียก `bash scripts/check-code.sh`
# ⇒ ลูกตัวนั้น **ไม่ใช่หัวหน้ากลุ่ม** มันรับ PGID ของ `verify.sh` มา ⇒ `kill -- -$$` ที่นั่น
# ไม่มีกลุ่มให้ยิง (เงียบ) หรือแย่กว่านั้นคือยิงไปโดน**ทั้งสายของ `verify.sh` เอง**
# ⇒ ทางที่ถูกคือ **สร้างกลุ่มใหม่ให้งานลูก แล้วยิงเฉพาะกลุ่มนั้น** — กลุ่มที่สคริปต์นี้สร้างเอง
# ไม่มีทางเป็นของสายอื่น (ตรงเจตนาของ §6 rule 6: ระบุตัวให้ชัดก่อนฆ่า ห้ามยิงตาม pattern)
#
# ## ทำไมจดลง**ไฟล์** ไม่ใช่ตัวแปร
# `check-code.sh` เรียกตัวรันในไปป์ไลน์ (`rust_run … | tee "$DB_LOG"`) ⇒ ตัวฟังก์ชันทำงานใน
# **subshell** ⇒ ตัวแปรที่ตั้งข้างในมองไม่เห็นจากตัว `cleanup` ที่อยู่ในเชลล์แม่ · และงานที่
# ต้องฆ่าให้ได้ที่สุดคือ stage db ซึ่งเป็น**ตัวที่อยู่ในไปป์ไลน์นั้นพอดี**
#
# ## กติกาที่ต้องถือไว้
# **ล้างเลขทิ้งทันทีที่งานจบเอง** — ไฟล์ที่เป็นสุสานแปลว่า `cleanup` จะยิงสัญญาณไปที่กลุ่มของ
# pid ที่ถูก**ใช้ซ้ำ**ไปแล้ว ซึ่งคือการฆ่าของคนอื่นโดยไม่ตั้งใจ แบบเดียวกับที่ใบ 121 เจอ

# ตั้งบ้านของไฟล์ก่อนใช้ — ผู้เรียกกำหนดเอง (ผูกกับ RUN_ID ของรอบตัวเอง)
JOB_GROUP_FILE="${JOB_GROUP_FILE:-}"

# รัน `"$@"` ในกลุ่มของตัวเอง แล้วคืน exit code ของมันตรง ๆ
job_group_run() {
  [ -n "$JOB_GROUP_FILE" ] || { echo "job-group: ไม่ได้ตั้ง JOB_GROUP_FILE" >&2; return 1; }
  local pgid status
  # `set -m` = เปิด job control ⇒ งานเบื้องหลังได้ **process group ของตัวเอง** และ PGID = PID
  # ของมัน · ปิดกลับทันทีเพื่อไม่ให้ไปเปลี่ยนพฤติกรรมของโค้ดส่วนอื่นในสคริปต์ผู้เรียก
  set -m
  "$@" &
  pgid=$!
  set +m
  printf '%s\n' "$pgid" > "$JOB_GROUP_FILE"
  wait "$pgid"
  status=$?
  : > "$JOB_GROUP_FILE"
  return "$status"
}

# ฆ่ากลุ่มที่จดไว้ (ถ้ามี) — เรียกจาก `cleanup` ของผู้เรียก
job_group_kill() {
  [ -n "$JOB_GROUP_FILE" ] && [ -s "$JOB_GROUP_FILE" ] || return 0
  local pgid
  while read -r pgid; do
    case "$pgid" in
      ''|*[!0-9]*) continue ;;  # อ่านเจออะไรที่ไม่ใช่เลข = ไม่ยิง (ห้ามเดา)
    esac
    kill -- "-$pgid" 2>/dev/null || true
  done < "$JOB_GROUP_FILE"
  : > "$JOB_GROUP_FILE"
}
