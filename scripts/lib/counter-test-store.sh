now() { date +%s; }

age_th() { # วินาที → ข้อความไทย · อายุคือสิ่งที่ทำให้ "สำเนาข้ามรอบ" มองเห็นได้ด้วยตา
  local s="$1"
  if [ "$s" -lt 60 ]; then echo "${s} วินาทีที่แล้ว"
  elif [ "$s" -lt 3600 ]; then echo "$((s / 60)) นาทีที่แล้ว"
  elif [ "$s" -lt 86400 ]; then echo "$((s / 3600)) ชั่วโมง $(((s % 3600) / 60)) นาทีที่แล้ว"
  else echo "$((s / 86400)) วัน $(((s % 86400) / 3600)) ชั่วโมงที่แล้ว"
  fi
}

# ⚠️ **ห้ามส่ง `ts` ที่อ่านจาก manifest เข้า `$(( ))` ตรง ๆ** — bash ขยาย array subscript
# ข้างในบริบทเลขคณิต ⇒ `ts` ที่เป็น `p[$(cmd)]` **รันคำสั่งนั้นจริง** · และ `status` คือคำสั่งเดียว
# ที่อ่าน manifest ของ **สายอื่น** โดยไม่ผ่าน `owner_check` ⇒ ไฟล์ที่ดีไซน์นี้ถือว่าไม่น่าเชื่อถือ
# ถูกป้อนเข้าบริบทที่ประเมินค่า · อีกครึ่งคือแถวเสียทำให้ `set -u` ฆ่าลูป restore ตั้งแต่แถวแรก
# ⇒ แถวหลังจากนั้นไม่ถูกคืนและไม่ถูกเอ่ยชื่อเลย (พิสูจน์แล้วทั้งสองครึ่ง)
age_of() { # <ค่าที่อ่านจากไฟล์> → ข้อความอายุ
  case "${1:-}" in
    ''|*[!0-9]*) echo "เวลาในแถวเสีย อ่านอายุไม่ได้" ;;
    *) age_th "$(( $(now) - $1 ))" ;;
  esac
}

# manifest ที่บรรทัดสุดท้ายเขียนค้าง (ไม่จบด้วยขึ้นบรรทัดใหม่) = **นับของในคลังไม่ได้**
# `cut -f1` เห็นแถวนั้น แต่ `read` ไม่เห็น (คืน non-zero บนบรรทัดที่ไม่มีตัวจบ) ⇒ สองตัวอ่าน
# ไม่ตรงกัน ⇒ restore ข้ามไฟล์ที่ถืออยู่ **แล้วพิมพ์บรรทัดสำเร็จ + `rm -rf` สำเนาใบเดียวทิ้ง**
# ซึ่งคือคลาสหัวเรื่องของใบ 187 เป๊ะ ๆ มาทางเส้นใหม่ · เกิดได้จาก short write จริง (ดิสก์เต็ม/quota)
