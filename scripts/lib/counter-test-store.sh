# เลือกเครื่องคิดแฮช **ครั้งเดียวตอนเริ่ม** — เลือกในฟังก์ชันที่ถูกเรียกใน `$( )` แปลว่า
# `exit` ของมันตายอยู่ใน subshell แล้วตัวหลักเดินต่อด้วยแฮชเปล่า (เขียวปลอมชนิดที่แย่ที่สุด)
if command -v sha256sum >/dev/null 2>&1; then SHA_CMD="sha256sum"
elif command -v shasum >/dev/null 2>&1; then SHA_CMD="shasum -a 256"
else
  echo "counter-test: เครื่องนี้ไม่มี sha256sum/shasum — ยืนยันการคืนไม่ได้ จึงไม่รับงาน" >&2
  exit 4
fi
sha256_of() { $SHA_CMD "$1" | cut -d' ' -f1; }

# ⚙️ **นี่คือ "การแก้" ของราก 1 ทั้งก้อน อยู่ในบรรทัดเดียว** — selftest ถอนบรรทัดในนี้ออก
# (เคส S1) เพื่อพิสูจน์ว่าเคสสำเนาเน่าแดงเพราะสิ่งนี้จริง ๆ ไม่ใช่เพราะเหตุอื่น
verify_sha() { # <ไฟล์> <แฮชที่จดตอน save> → 0 เมื่อตรง
  [ "$(sha256_of "$1")" = "$2" ]
}

