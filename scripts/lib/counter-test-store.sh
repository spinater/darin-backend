manifest_refuse() {
  echo "counter-test: $manifest บรรทัดสุดท้ายเขียนค้าง (ไม่จบด้วยขึ้นบรรทัดใหม่)" >&2
  echo "              ⇒ นับของในคลังไม่ได้ จึงไม่คืนทับและไม่ลบคลัง · ดู \`status\`" >&2
  exit 1
}

canon() { # อาร์กิวเมนต์ → พาธสัมพัทธ์กับรากรีโป · ปฏิเสธของนอกราก (คลังต่อสายไม่มีความหมาย
          # ถ้ายังตอบไม่ได้ว่า "ทรีไหน")
  local a="$1" d b p
  case "$a" in /*) p="$a" ;; *) p="$caller_pwd/$a" ;; esac
  d="$(dirname "$p")"; b="$(basename "$p")"
  [ -d "$d" ] || { echo "counter-test: ไม่มีไดเรกทอรี $d" >&2; return 1; }
  d="$(cd "$d" && pwd -P)" || return 1
  p="$d/$b"
  case "$p" in
    "$root"/*) printf '%s' "${p#"$root"/}" ;;
    *) echo "counter-test: $a อยู่นอกรีโปนี้" >&2
       echo "              ราก: $root · ไฟล์: $p" >&2
       return 1 ;;
  esac
}

# ⚠️ ต้องทนไฟล์ที่ไม่มี — GNU `sed` คืน **2** บนไฟล์ที่หายไป แล้ว `pipefail` + `set -e`
# ฆ่าสคริปต์กลางคันเงียบ ๆ ⇒ `status` (คำสั่งเดียวที่อ่านคลังของสายอื่น และเป็นคำสั่งเดียว
# ที่บอกได้ว่าคลังพังอยู่) ตายก่อนพิมพ์บรรทัดของคลังใบนั้นพอดี
owner_get() {
  local f="${2:-$owner_file}"
  [ -f "$f" ] || return 0
  sed -n "s/^$1=//p" "$f" 2>/dev/null | head -1 || true
}

owner_write() {
  { echo "lane=$lane"
    # **lane ดิบ** ด้วย — `tr -c 'A-Za-z0-9._-' '_'` ไม่ injective (`a/b` · `a b` · `a*b`
    # ยุบเป็น `a_b` เหมือนกันหมด) ⇒ ถ้าเทียบแค่ชื่อไดเรกทอรี สองสายคนละชื่อจะกลายเป็นสายเดียว
    # แล้วอาการที่ 2 ของใบ 187 กลับมาทั้งดุ้น (วัดจริง: สาย `a b` คืนสำเนาของสาย `a/b` ทับงานตัวเอง
    # พิมพ์บรรทัดสำเร็จ แล้ว `rm -rf` คลังของอีกสายทิ้ง)
    echo "raw=$lane_raw"
    echo "tier=$lane_tier"
    echo "root=$root"
    echo "host=$host"
    echo "pid=$owner_pid"
    echo "opened_at=$(now)"
  } > "$owner_file"
}

# ตรวจความเป็นเจ้าของ **ก่อนแตะอะไรทั้งสิ้น** — คืนไม่ 0 = ผู้เรียกต้องหยุด
# เทียบ pid ด้วย เพราะสองสายอาจได้ session id เดียวกัน (วัดจริงบนเครื่องนี้: สอง process ของ
# claude ที่มีชีวิตพร้อมกัน carry ค่าเดียวกันมาจากบรรพบุรุษร่วม) ⇒ ชื่อไดเรกทอรีอย่างเดียวแยกไม่ออก
owner_check() {
  local o_root o_host o_pid o_raw
  if [ ! -f "$owner_file" ]; then
    echo "counter-test: คลัง $store ไม่มี owner.txt — พิสูจน์ไม่ได้ว่าเป็นของใคร จึงไม่แตะ" >&2
    return 1
  fi
  o_root="$(owner_get root)"; o_host="$(owner_get host)"; o_pid="$(owner_get pid)"
  o_raw="$(owner_get raw)"
  if [ "$o_root" != "$root" ] || [ "$o_host" != "$host" ] || [ "$o_pid" != "$owner_pid" ] \
     || [ "$o_raw" != "$lane_raw" ]; then
    echo "counter-test: คลัง $store เป็นของสายอื่น — ไม่แตะ" >&2
    echo "              ของเขา: lane=$o_raw root=$o_root host=$o_host pid=$o_pid" >&2
    echo "              ของเรา: lane=$lane_raw root=$root host=$host pid=$owner_pid" >&2
    echo "              ⇒ ตั้ง COUNTER_TEST_LANE=<ชื่อที่ไม่ซ้ำ> แล้วสั่งใหม่ (ดู \`status\`)" >&2
    echo "              ถ้าต้องการของในคลังนั้นจริง ๆ ให้อ่าน $manifest แล้ว \`cp\` เองด้วยมือ —" >&2
    echo "              การเขียนทับงานตัวเองด้วยสำเนาที่พิสูจน์เจ้าของไม่ได้ ต้องมีคนกดเอง" >&2
    return 1
  fi
  return 0
}

