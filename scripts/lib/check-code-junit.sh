      # หัวไฟล์ประกาศรูปแถวไว้ว่าคอลัมน์ที่สามขึ้นต้นด้วย `#` ⇒ ยามต้องบังคับตามที่ประกาศ
      # ไม่งั้นหัวไฟล์กับของจริงพูดคนละเรื่อง ซึ่งเป็นคลาสเดียวกับคอมเมนต์ที่อ้างด่านที่ไม่มีอยู่
      case "$note" in
        '#'*) ;;
        *) echo "check-code: FAIL — $PINS_FILE: แถว '$suite' คอลัมน์ที่สามไม่ได้ขึ้นต้นด้วย '#' ⇒ รูปแถวผิด"; fail=1; continue ;;
      esac
      case "$note" in
        *'ใบ '[0-9][0-9][0-9]*) ;;
        *) echo "check-code: FAIL — $PINS_FILE: แถว '$suite' ไม่ได้อ้าง 'ใบ NNN' ⇒ ไม่มีใครรู้ว่าหมุดนี้มาจากงานไหน"; fail=1; continue ;;
      esac
      case "$pin_seen" in
        *"|$suite|"*) echo "check-code: FAIL — $PINS_FILE: '$suite' มีสองแถว ⇒ แถวหลังบังแถวแรกเงียบ ๆ"; fail=1; continue ;;
      esac
      pin_seen="$pin_seen|$suite|"
      pin_rows=$((pin_rows + 1))
      # `index(… ) == 1` = เทียบสตริงตรง ๆ จากต้นบรรทัด (ชื่อไฟล์มี `.` ซึ่งเป็น metachar ของ regex)
      ran="$(awk -F'\t' -v s="$suite" 'index($0, s "\t") == 1 { print $2; exit }' "$JUNIT_SUITES")"
      case "$ran" in
        "")
          echo "check-code: FAIL — $suite ไม่ได้ถูกรัน (ถูกลบ/เปลี่ยนชื่อ?)"
          fail=1; continue ;;
        0|-*)
          echo "check-code: FAIL — $suite ถูกโหลดแต่ไม่มีเทสไหนทำงานจริง (skip ทั้งใบ?) ⇒ เกตหายไปแล้ว"
          fail=1; continue ;;
      esac
      # ── เทียบ **จำนวนเทสที่รันจริง แบบเท่ากันเป๊ะ** (ใบ 298)
      # ก่อนหน้านี้ทั้งสองแขนนับต่อ **ไฟล์** ⇒ ไฟล์ที่มีเทสหลายใบ **ลบไปใบหนึ่งแล้วยังเขียวทั้งคู่**
      # (วัดจริงที่ `tests/messages/customer-facing-terms.test.ts`: ลบยามคำต้องห้ามทั้งอันทิ้ง เหลือ
      # เทสตัวช่วยสองใบ ⇒ junit `tests="2" skipped="0"` ⇒ หมุดเขียว · `tsc` ก็เงียบเพราะ
      # `noUnusedLocals` ไม่ได้ตั้ง) ⇒ **เหตุผลของการมีชั้นที่หนึ่งหายไปพร้อมกัน**
      #
      # 🔑 **ใบอนุญาตให้ใช้ `==`**: ลูปที่ผลิตเทสในไฟล์ที่ปักไว้วนบน `const` ที่ประกาศ **ในไฟล์เทสเอง**
      # ไม่มีใบไหนวนบนรายชื่อไฟล์จากดิสก์ และไม่มี `test.skip`/`skipIf`/เงื่อนไข env ที่จุดประกาศเทส
      # ⇒ จำนวนเทสเป็น **ฟังก์ชันบริสุทธิ์ของทรี** ⇒ ไม่ flake ข้ามรอบ ข้ามเครื่องยนต์ native/docker
      #
      # ⚠️ **สองแขนแยกกัน ไม่ใช่ `!=` ก้อนเดียว โดยตั้งใจ** — สองทิศมี *ทางแก้คนละอย่าง* (ทิศโต =
      # ยกหมุด · ทิศหด = ประกาศว่า coverage หายไปจริง) ⇒ ต้องเป็นคนละข้อความ · และการแยกโค้ด
      # คือสิ่งที่ทำให้แถวความไว S3/S7 พลิกทีละแขนได้จริง แทนที่จะแดงพร้อมกันทั้งพวง
      if [ "$ran" -gt "$want" ]; then
        echo "check-code: FAIL — $suite รันจริง $ran เทส แต่หมุดไว้ $want"
        echo "             ⇒ เพิ่มเทส/แถวทะเบียนแล้วยังไม่ยกหมุด · แก้แถวของไฟล์นี้ที่ $PINS_FILE เป็น $ran"
        fail=1
      elif [ "$ran" -lt "$want" ]; then
        echo "check-code: FAIL — $suite รันจริง $ran เทส แต่หมุดไว้ $want"
        echo "             ⇒ มีเทสหายไป $((want - ran)) ใบ (ถูกลบ หรือถูก test.skip เดี่ยว ๆ)"
        echo "             ถ้าตั้งใจลบ: แก้เลขในแถวของไฟล์นี้ที่ $PINS_FILE แล้วเขียนเหตุผลในใบงาน"
        fail=1
      fi
    done < "$PINS_FILE"
    if [ "$pin_rows" -eq 0 ]; then
      echo "check-code: FAIL — $PINS_FILE อ่านได้ 0 แถว ⇒ ตัวอ่านพังหรือไฟล์ว่าง ไม่ใช่ 'ไม่มีหมุด'"
      fail=1
    fi
  fi

  # ### ชั้นที่สอง — กวาดทั้งชุด: ทิศ "ไฟล์ยังอยู่แต่ไม่ได้รัน" (ใบ 215)
  # คอร์ปัสมาจาก **กิต ไม่ใช่ `find`** และเป็น `-c -o --exclude-standard` ชุดเดียวกับ
  # `scripts/lib/file-length-scope.sh` ⇒ ไฟล์เทสที่เพิ่งเขียนแต่ยังไม่ `git add` ก็อยู่ในคอร์ปัส
  # ⇒ **เพิ่มไฟล์เทสใหม่ไม่ทำให้เกตแดง** (คำถามที่ใบ 215 สั่งให้วัดก่อนตัดสิน — วัดแล้ว: ไฟล์ใหม่
  # อยู่ทั้งในคอร์ปัสและใน junit พร้อมกัน) · ที่แดงคือไฟล์ที่ *มีอยู่แต่ไม่ทำงาน* เท่านั้น
  # ⚠️ รูปชื่อไฟล์เทสยังเป็น "รายการ" อยู่ (ของ bun ไม่ใช่ของเรา) — ที่กันไม่ให้มันเงียบคือ
  # **ทิศกลับ**: ชุดระดับไฟล์ใน junit ที่ไม่อยู่ในคอร์ปัส = แดงพร้อมชื่อ ไม่ใช่ไม่ถูกตรวจเงียบ ๆ
  # (เช่นวันที่มีคนเขียนไฟล์เทสในรูปชื่อที่ bun รันแต่ `case` ข้างล่างไม่จับ — §6 rule 1
  # บอกว่าทิศที่ผิดต้องเป็น **false red ที่แก้ในนาทีเดียว** ไม่ใช่ความเงียบ)
  # ⚠️ `-c` ยังคายไฟล์ที่ **ถูกลบจาก worktree แต่ยังอยู่ใน index** ออกมาด้วย ⇒ ต้องกรองด้วย
  # `[ -f ]` ไม่งั้นไฟล์ที่เพิ่งถูกลบจะได้ข้อความ "มีอยู่จริงแต่ไม่มีเทสไหนทำงาน" ซึ่งเป็นเท็จ
  # และชี้ไปคนละทางกับสาเหตุ · ทิศ "ถูกลบ" เป็นงานของชั้นที่หนึ่ง ไม่ใช่ของการกวาด
  # `-z` (ใบ 314) — `git ls-files` เปล่า ๆ quote พาธที่ไม่ใช่ ASCII ⇒ `"` ท้ายชื่อทำให้ `case`
  # ข้างล่างไม่แมตช์ `*.test.ts` ⇒ ไฟล์เทสชื่อไทยหล่นจากคลังก่อนถึง `[ -f ]` เสียอีก
  # วันนี้รอดเพราะ pathspec `-- web` (ยังไม่มีพาธที่ไม่ใช่ ASCII ใต้ web/) **ไม่ใช่เพราะโค้ด**
  # · ทิศกลับของชั้นนี้จะแดงให้เอง (bun เขียนชื่อไฟล์ดิบลง junit ⇒ `comm -13` ฟ้อง) แต่นั่นคือ
  # การกันของอีกชั้น ไม่ใช่ของตัวคลังเอง ⇒ แก้ที่ต้นทาง · ไฟล์คลังยังคั่นด้วยขึ้นบรรทัดใหม่
  # เหมือนเดิม ⇒ `LC_ALL=C sort -u` กับ `comm` ข้างล่างไม่ต้องเปลี่ยน
  # darin: เทสอยู่ที่ **รากรีโป** (`lib/*.test.ts`) ไม่ได้อยู่ใต้ web/ แบบ groove-clinic
  # ⇒ รากคอร์ปัสเป็นตัวแปร ไม่ใช่ค่าคงที่ที่ฝังในสำนวน git (selftest ตั้งค่านี้เองด้วย)
  JUNIT_CORPUS_ROOT="${JUNIT_CORPUS_ROOT:-.}"
  git ls-files -c -o --exclude-standard -z -- "$JUNIT_CORPUS_ROOT" > "$JUNIT_SUITES.files"
  : > "$JUNIT_SUITES.corpus"
  while IFS= read -r -d '' f; do
    case "$f" in *.test.js|*.test.jsx|*.test.ts|*.test.tsx|*.spec.js|*.spec.jsx|*.spec.ts|*.spec.tsx) ;;
      *) continue ;; esac
    # ชื่อชุดใน junit คือพาธเทียบ cwd ของ `bun test` ⇒ ตัด prefix เฉพาะตอนที่รากไม่ใช่ "."
    case "$JUNIT_CORPUS_ROOT" in
      .) rel="$f" ;;
      *) rel="${f#"$JUNIT_CORPUS_ROOT"/}" ;;
    esac
    if [ -f "$f" ]; then printf '%s\n' "$rel" >> "$JUNIT_SUITES.corpus"; fi
  done < "$JUNIT_SUITES.files"
  # 🔴 **`LC_ALL=C` ทั้งสามชุด และมันไม่ใช่ความระมัดระวังลอย ๆ — วัดแล้ว** (ใบ 302)
  # `sort` เปล่า ๆ เรียงตาม **locale** ส่วน `comm` เทียบแบบ **ไบต์** ⇒ สองฝั่งสมมติคนละลำดับ ·
  # เครื่องนี้ใช้ uutils `sort` 0.8.0 ใต้ `en_US.UTF-8` ซึ่งให้เครื่องหมายวรรคตอน **น้ำหนักการเรียง
  # เป็นศูนย์** ⇒ บนคลังจริง 162 ใบมี **18 บรรทัดอยู่คนละตำแหน่ง** (`tests/contract/…` มาก่อน
  # `tests/contract-…` ตามลำดับ locale แต่มาทีหลังตามลำดับไบต์ — `/` = 0x2F · `-` = 0x2D)
  # ⇒ `comm` พ่น **สามบรรทัดจากการเปรียบเทียบเดียว** (`file 1` · `file 2` · `input is not in
  # sorted order`) — ⚠️ **ไม่ใช่ "ทั้งสามการเปรียบเทียบ"**: ที่นี่มี `comm` แค่ **สอง** ตัว และ
  # ตัวที่สองเงียบ · เลขเก่าถูกยกข้ามมาจากการวัด *ลำดับ* (18 บรรทัดอยู่คนละตำแหน่ง) คนละเรื่องกัน
  # · รอบที่เจอคำตัดสินบังเอิญถูก แต่ **`comm` บน input ที่ไม่ได้เรียงไม่รับประกันอะไรเลย** และ
  # ทิศที่อันตรายคือ **เขียวปลอม**: ไฟล์เทสที่หายไปอาจไม่ถูกรายงานว่าหาย ซึ่งเป็น *งานเดียว*
  # ของชั้นนี้ · ⚠️ ห้ามถอด `LC_ALL=C` ออกด้วยเหตุผลว่า "เครื่องผมเรียงเหมือนกัน" — นั่นคือ
  # คุณสมบัติของ locale ที่คุณบังเอิญตั้งไว้ ไม่ใช่ของโค้ด (กับดัก uutils ตัวเดียวกับที่ §7 จดไว้
  # ตอน `sort | uniq -c` นับหัวการ์ดเป็นกลุ่มสุ่ม)
  #
  # 🔴 **`-u` ด้วย และมันไม่ใช่ของแถม — `comm` สมมติว่า input *ไม่ซ้ำ* พอ ๆ กับที่สมมติว่าเรียง**
  # `git ls-files -c` คายพาธเดียวกัน **สามครั้ง** ตอนไฟล์นั้นค้าง merge conflict (stage 1/2/3 —
  # วัดจริงด้วยรีโปทดลอง) ⇒ คลังมีบรรทัดซ้ำ ⇒ `comm -23` พ่นข้อความ **ซ้ำสามครั้งสำหรับไฟล์เดียว**
  # ซึ่งเป็น "แดงที่เรียกชื่อสาเหตุผิด" คลาสเดียวกับที่แขนคอร์ปัสว่างข้างล่างเพิ่งปิด · และเครื่องนี้
  # merge สายขนานเป็นกิจวัตร ⇒ ไม่ใช่ฉากสมมติ
  # ⚠️ **`-u` ปลอดภัยที่นี่ *เพราะ* อยู่ใต้ `LC_ALL=C` แล้ว** — ใต้ `en_US.UTF-8` uutils ให้วรรคตอน
  # น้ำหนักศูนย์ ⇒ `sort -u` **ยุบชื่อที่ต่างกันจริง** (วัด: `a-b`=`a_b`=`ab` · `foo_bar`=`foobar`
  # · 7 บรรทัดเหลือ 3) ⇒ ใส่ `-u` โดยไม่มี `LC_ALL=C` คือเปลี่ยนบั๊กหนึ่งเป็นอีกบั๊กที่เงียบกว่า
  # ⇒ **สองอย่างนี้ต้องมาคู่กันเสมอ ห้ามแยก** (จุดอื่นในรีโปที่ยังเปล่าอยู่ = ใบ 304)
  LC_ALL=C sort -u -o "$JUNIT_SUITES.corpus" "$JUNIT_SUITES.corpus"
  awk -F'\t' '$2 > 0 { print $1 }' "$JUNIT_SUITES" | LC_ALL=C sort -u > "$JUNIT_SUITES.ran"
  cut -f1 "$JUNIT_SUITES" | grep -v '^!' | LC_ALL=C sort -u > "$JUNIT_SUITES.seen" || true
  # 🔴 **คอร์ปัสว่าง = FAIL ไม่ใช่ "ตรวจครบแล้วไม่เจออะไร"** (ใบ 302) — ก่อนหน้านี้บรรทัดพิมพ์
  # จำนวนข้างล่างอ้างบทเรียนใบ 193 ไว้ตรง ๆ **แต่ไม่มีแขนไหน FAIL เลย** ⇒ วันที่
  # `git ls-files -- web` คืนว่าง (cwd ผิด · ไม่ได้อยู่ในรีโป · sparse checkout · web/ ถูกย้าย)
  # ชั้นที่สองจะ "ตรวจศูนย์ไฟล์แล้วเขียว" ซึ่งคือเกตที่หายไปโดยไม่มีใครรู้ — โรคเดียวกับที่
  # `scripts/check-file-length.sh` แบกอยู่ 193 ใบงาน · **และข้ามลูป `comm` ทั้งสองด้วย**
  # ด้วยเหตุผลเดียวกับแขน `[ ! -s "$WEB_JUNIT" ]` ข้างบน: อ่าน input ไม่ได้แล้วเดินต่อ =
  # รายงานที่ชี้ผิดทาง (คอร์ปัสว่าง ⇒ `comm -13` จะฟ้องว่า *ทุก* ชุดใน junit ไม่อยู่ในคอร์ปัส
  # ซึ่งเป็นน้ำท่วมที่กลบสาเหตุจริง — คลาสเดียวกับข้อความเท็จที่ตัวกรอง `[ -f ]` กันไว้)
  if [ ! -s "$JUNIT_SUITES.corpus" ]; then
    echo "check-code: FAIL — กวาดไฟล์เทสได้ 0 ใบ ⇒ ตัวคัดไฟล์พัง ไม่ใช่ 'รีโปไม่มีเทส' (cwd ผิด/ไม่ใช่รีโป/sparse checkout?)"
    fail=1
  elif [ ! -s "$JUNIT_SUITES.seen" ]; then
    # **แขนสมมาตรของข้างบน — ฝั่ง junit ว่างบ้าง** · junit ที่ไม่มีชุด *ระดับไฟล์* เลยสักใบ
    # (`name != file` ทุกแถว) ทำให้ `.seen` และ `.ran` ว่างทั้งคู่ โดยแขน `!unreadable` ไม่ยิง
    # (attribute อ่านได้ครบ แค่ไม่มีแถวไหนเป็นชุดระดับไฟล์) ⇒ `comm -23` จะพ่น "มีอยู่จริงแต่ไม่มี
    # เทสไหนทำงาน" **ทุกไฟล์ในคลัง** = น้ำท่วมที่เรียกชื่อสาเหตุผิดแบบเดียวกับที่แขนแรกเพิ่งปิด
    # · `.seen` ว่างเกิดได้เฉพาะกรณีหายนะ (ไม่มีชุดระดับไฟล์เลยทั้งรายงาน) ⇒ ไม่บังตาเคสปกติ
    # · ชั้นที่หนึ่งยังรายงานหมุดของตัวเองตามปกติ ซึ่งเรียกชื่อสาเหตุถูกอยู่แล้ว
    echo "check-code: FAIL — junit ไม่มีชุดระดับไฟล์เลยสักใบ (name == file ไม่ตรงสักแถว) ⇒ รูปรายงานเปลี่ยน หรือ bun ไม่ได้รันอะไรเลย"
    fail=1
  else
    while IFS= read -r f; do
      [ -n "$f" ] || continue
      echo "check-code: FAIL — $f มีอยู่จริงแต่ไม่มีเทสไหนทำงาน (skip ทั้งใบ/ไฟล์ว่าง?)"
      fail=1
    done < <(comm -23 "$JUNIT_SUITES.corpus" "$JUNIT_SUITES.ran")
    while IFS= read -r f; do
      [ -n "$f" ] || continue
      echo "check-code: FAIL — junit มีชุด $f ที่ไม่อยู่ในคอร์ปัส ⇒ การกวาดมองไม่เห็นไฟล์นี้"
      fail=1
    done < <(comm -13 "$JUNIT_SUITES.corpus" "$JUNIT_SUITES.seen")
  fi
  # **พิมพ์จำนวนที่กวาดทุกรอบ** — พิมพ์แม้ตอนเป็นศูนย์ (แขนข้างบนแดงไปแล้ว) เพราะคนอ่าน log
  # ต้องเห็น *ตัวเลข* ไม่ใช่แค่คำว่าพัง
  echo "check-code: กวาดไฟล์เทส $(wc -l < "$JUNIT_SUITES.corpus") ใบ"
fi
