    # vendored shadcn output (§4) — ของที่ generate มา ไม่ใช่ของที่เราเขียน
    components/ui/* | */components/ui/*) return 0 ;;
    *.d.ts | *generated*) return 0 ;;
    # แตกแล้วความหมายเปลี่ยน (§4) — และ migration ที่ apply แล้วถูก checksum ⇒ แก้ไม่ได้เลยด้วยซ้ำ
    migrations/* | */migrations/*) return 0 ;;
    # ไคลเอนต์ที่ prisma generate ออกมา (`generated/`) — ติด `*generated*` อยู่แล้ว
    # แถวนี้คือชั้นที่สองสำหรับผลลัพธ์ของ Next.js ที่อยู่นอก .gitignore ชั่วคราว
    .next/* | */.next/*) return 0 ;;
    # lockfile = เครื่องเขียน · "แตกเป็น sub-module" ไม่ใช่ทางแก้ของมันในทุกกรณี
    # ⇒ ใส่ allowlist หนี้ไม่ได้ด้วย เพราะแถวนั้นจะไม่มีวันถูกปลด = สุสานที่กติกาห้าม
    *.lock | *-lock.json) return 0 ;;
    # ซ้ำซ้อนกับ `.gitignore` โดยตั้งใจ (ดูหัวไฟล์) — ผิดได้แค่ทางแดงปลอม
    node_modules/* | */node_modules/*) return 0 ;;
    target/* | */target/*) return 0 ;;
  esac
  return 1
}

flen_is_binary() { # $1 = พาธจริงที่อ่านได้ ; return 0 = binary
  # `grep -I` ถือว่าไฟล์ binary "ไม่แมตช์" ⇒ `-Iq .` เป็นตัวตรวจ **จากเนื้อไฟล์**
  # · ไฟล์ว่างก็ไม่แมตช์เหมือนกัน แต่ 0 บรรทัดไม่มีทางชนเพดาน ⇒ ผู้เรียกกันไว้ด้วยการนับก่อน
  ! grep -Iq . "$1" 2>/dev/null
}

flen_gitignored() { # $1 = พาธ ; return 0 = git บอกว่าถูก ignore (ไม่มี git = ตอบ "ไม่" ให้ผู้เรียกตัดสินเอง)
  command -v git >/dev/null 2>&1 || return 1
  git check-ignore -q -- "$1" 2>/dev/null
}

flen_rel() { # $1 = พาธ ; $2 = รากรีโป ; stdout = พาธสัมพัทธ์ (นอกรีโป/บอกไม่ได้ = คืนตามเดิม)
  case "${2:-}" in
    "") printf '%s\n' "$1" ;;
    *) case "$1" in
      "$2"/*) printf '%s\n' "${1#"$2"/}" ;;
      *) printf '%s\n' "$1" ;;
    esac ;;
  esac
}

flen_allowlist_rows() { # stdout = "<เลขบรรทัด>\t<พาธ>\t<ส่วนที่เหลือ>" เฉพาะแถวจริง ($1 = พาธ allowlist)
  local file="${1:-$FLEN_ALLOWLIST}" n=0 line path rest
  [ -f "$file" ] || return 0
  while IFS= read -r line || [ -n "$line" ]; do
    n=$((n + 1))
    case "$line" in '' | '#'*) continue ;; esac
    path="${line%%[[:space:]]#*}"
    path="${path%"${path##*[![:space:]]}"}"
    rest="${line#"$path"}"
    [ -n "$path" ] || continue
    printf '%s\t%s\t%s\n' "$n" "$path" "$rest"
  done < "$file"
}

flen_waived() { # $1 = พาธ ; $2 = พาธ allowlist (ไม่ใส่ = ค่าเริ่มต้น) ; return 0 = มีแถวยกหนี้อยู่
  local p="$1" a
  # ⚠️ **เทียบเป็นสตริงตรง ๆ ห้ามใช้ `case`** — พาธจริงของ Next.js มี `[locale]` กับ `(app)`
  # อยู่ด้วย ซึ่ง `case` อ่านเป็น glob แล้วยกเว้นเกินจริง (บทเรียนใบ 190 คำต่อคำ)
  while IFS=$'\t' read -r _ a _; do
    [ "$p" = "$a" ] && return 0
    # hook ได้พาธ**สัมบูรณ์**มาเมื่อ `flen_rel` ตัดรากรีโปออกไม่สำเร็จ (เช่นรากที่เป็น symlink)
    # ⇒ ยอมให้ลงท้ายตรงกันทั้งเซกเมนต์ **เฉพาะพาธสัมบูรณ์เท่านั้น**
    #
    # 🔴 **`/*` ข้างนอกนี่ไม่ใช่ของประดับ** — การกวาดทั้งรีโปส่งพาธ *สัมพัทธ์* จาก `git ls-files`
    # เข้ามาเสมอ ⇒ ถ้าปล่อยให้แขนนี้ยิงกับพาธสัมพัทธ์ด้วย **หนึ่งแถวจะยกหนี้ให้ไฟล์ทั้งตระกูล
    # ที่พาธ "ลงท้ายเหมือนกัน" โดยที่ไม่มีใครใส่มันไว้ในลิสต์** และด่านกันสุสานทั้งสามทิศมองไม่เห็น
    # เพราะมันเดินตาม *แถว* ไม่ได้เดินตาม *ไฟล์* ⇒ เกตพิมพ์ `ยกหนี้ไว้ใน …` เกี่ยวกับไฟล์ที่ไม่มีแถว
    # แล้ว exit 0 · วัดจริงตอนรีวิวใบ 193: แถวของแคตตาล็อก i18n ภาษาไทยใบเดียว (ตอนนั้นยังเป็น
    # ไฟล์เดียว 3,084 บรรทัด ก่อนใบ 194 แตกเป็น web/src/messages/th/) ยกหนี้ให้ไฟล์ชื่อเดียวกัน
    # ใต้ `packages/admin/` ที่ไม่ได้อยู่ในลิสต์เลย (เคส W ของ selftest เฝ้าอยู่) — **เขียนพาธเก่า
    # ตรง ๆ ไม่ได้** เพราะ allowlist ของ `check-card-paths.sh` คีย์ด้วย *พาธ* ไม่ใช่ *จุดอ้าง*
    # ⇒ ยกเว้นให้ประโยคนี้ = ปิดตาด่านทุกที่ในรีโปที่อ้างพาธนั้น (ใบ 195)
    case "$p" in /*) case "$p" in */"$a") return 0 ;; esac ;; esac
  done < <(flen_allowlist_rows "${2:-$FLEN_ALLOWLIST}")
  return 1
}
