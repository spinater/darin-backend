# `-z` + `read -r -d ''` (ใบ 314) — และ **ตัวนับ** ที่ชั้นนี้ไม่เคยมี: ก่อนใบนี้ชั้นที่หนึ่ง
# ไม่พิมพ์จำนวนและไม่มีด่าน `กวาด 0 = FAIL` ⇒ การแก้ครึ่งเดียว (ใส่ `-z` ให้ต้นทางแต่ลืมตัวอ่าน)
# จะทำให้ลูปนี้วน **ศูนย์รอบ** แล้วเกตยังพิมพ์ OK — เงียบกว่าบั๊กเดิมที่ข้ามแค่ไฟล์ชื่อไทย
md_files=0
while IFS= read -r -d '' f; do
  md_files=$((md_files + 1))
  case "$f" in
    .docs/claude-skills-bundle/*) continue ;;
    # `.scratch/` = พื้นที่ทำงานที่ gitignore ไว้ (§6 rule 5) — ไฟล์ที่ force-add ชั่วคราว
    # เพื่อขนข้ามเครื่องไม่ใช่เอกสารของโปรเจกต์ จึงไม่ต้องมีลิงก์ที่ resolve ได้
    .scratch/*) continue ;;
  esac
  dir=$(dirname "$f")
  # markdown links: ](target) — strip fragments, skip absolute/external/empty
  while IFS= read -r target; do
    case "$target" in
      http://*|https://*|mailto:*|\#*|/*|"") continue ;;
    esac
    t="${target%%#*}"
    [ -z "$t" ] && continue
    if [ ! -e "$dir/$t" ]; then
      echo "FAIL: $f — broken link: $target"
      fail=1
    fi
  done < <(grep -oE '\]\([^)]+\)' "$f" 2>/dev/null | sed -E 's/^\]\(//; s/\)$//' || true)
done < <(git ls-files -c -o --exclude-standard -z '*.md')

if [ "$md_files" -eq 0 ]; then
