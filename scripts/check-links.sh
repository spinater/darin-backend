           | grep -oE '^[a-z][a-z-]*' || true)"
    [ -n "$tok" ] || unread=$((unread + 1))
    case "$tok" in
      todo|todo-human|done)
        if [ "$tok" != "$d" ]; then
          echo "FAIL: $f — บรรทัด status เขียน \`$tok\` แต่ใบอยู่บ้าน tasks/$d/"
          echo "      $st"
          echo "      (แก้ token ให้เป็น $d โดย**เก็บหางเหตุผลไว้** — หางคือข้อมูล ไม่ใช่ขยะ"
          echo "       หรือถ้าบ้านต่างหากที่ผิด ย้ายด้วย scripts/task-move.sh)"
          fail=1
        fi
        ;;
    esac

    # (ข) `- 🚫` = ประกาศว่าบล็อกที่คน ⇒ `todo-human/` บ้านเดียว
    if [ "$d" != "todo-human" ]; then
      num="$(basename "$f" | cut -c1-3)"
      while IFS= read -r hit; do
        [ -n "$hit" ] || continue
        echo "FAIL: $f:${hit%%:*} — บรรทัดขึ้นต้น \`- 🚫\` ประกาศว่าบล็อกที่คน แต่ใบอยู่บ้าน tasks/$d/"
        echo "      (ปลดบล็อกแล้ว ⇒ ลดชั้นเป็น \`- (เดิม) บล็อกที่: …\` แบบที่ใบ 166 ทำ —"
        echo "       ยังบล็อกอยู่จริง ⇒ bash scripts/task-move.sh $num --human)"
        fail=1
      done < <(grep -n '^- 🚫' "$f" || true)
    fi
  done
done
# ตัวเลือกไฟล์ที่เงียบ ๆ ไม่แมตช์อะไรเลย คือความล้มเหลวที่ `check-file-length.sh` ใช้เวลา 193 ใบ
# กว่าจะมีคนเห็น (§4) ⇒ กวาดได้ศูนย์ใบ = FAIL ไม่ใช่เขียว
if [ "$home_cards" -eq 0 ]; then
  echo "FAIL: ชั้นที่สี่อ่านใบงานได้ 0 ใบ — ตัวเลือกไฟล์พัง ไม่ใช่รีโปสะอาด"
  fail=1
else
  # พิมพ์ทุกรอบ — ทั้งขนาดคลังและ**กองที่อ่านไม่ออก** · ตัวเลขที่ไม่มีใครเห็น คือตัวเลขที่โตได้
  # โดยไม่มีใครรู้ (เหตุผลเดียวกับที่ `check-file-length.sh`/`check-card-paths.sh` พิมพ์คลังของตัวเอง)
  echo "check-links: ชั้นที่สี่ — หัวใบ $home_cards ใบ · token อ่านไม่ออก $unread ใบ (ไม่ได้อ้างบ้าน ⇒ ไม่ผิด)"
fi

# ── ชั้นที่สาม (task 168): พาธใบงานในไฟล์โค้ด ต้องมีไฟล์อยู่จริง **ที่บ้านที่พาธนั้นบอก**
# `--untracked` = เห็นไฟล์ใหม่ที่ยังไม่ `git add` ด้วย (เหมือน `-o` ของลูปข้างล่าง) และยัง
# เคารพ `.gitignore` ⇒ `.scratch/` ไม่หลุดเข้ามา · `|| true` เพราะ `git grep` คืน 1 เมื่อไม่เจอ
# อะไรเลย ซึ่งใต้ `set -euo pipefail` แปลว่าสคริปต์ตายกลางประโยค (บทเรียนเดียวกับ `ls` ข้างบน)
#
# **ตัดออกด้วย `:!` ไม่ใช่ระบุนามสกุลที่จะตรวจ** — รายการนามสกุลคือรายการที่ต้องมีคนไปเติม
# วันที่รีโปมีไฟล์ชนิดใหม่ (วันนี้ `.mjs` `.py` `.awk` `.yml` มีอยู่จริง แค่ยังไม่มีพอยน์เตอร์ในนั้น)
# และวันนั้นจะไม่มีใครรู้ตัว ⇒ ตรวจทุกอย่าง **ยกเว้น** `.md` (ชั้นที่หนึ่งดูแลอยู่แล้ว) กับบันเดิลที่
# vendor มา · `-I` = ข้ามไฟล์ binary (lock/รูป/pdf) ซึ่ง `-o` อ่านออกมาเป็นขยะได้
#
# 🔴 **`--no-color --no-column` ไม่ใช่ของประดับ** — บรรทัดข้างล่างตัดผลลัพธ์ตามตำแหน่ง
