# **FAIL 23 ใบ** (วัดแล้ว: 7 หัว migration + ทุกพอยน์เตอร์ที่ถูก + 7 ใบ "FROZEN เป็นสุสาน"
# เพราะ `frozen_seen` ว่าง) · `grep.column = true` เลื่อนฟิลด์แบบเดียวกันจนได้ข้อความที่
# **ขัดแย้งในตัวเอง**: บอกว่าพาธผิด แล้วบอกบ้านจริงเป็นพาธเดียวกันเป๊ะ
# ⇒ ทิศของบั๊กนี้คือ **แดงปลอม ไม่ใช่เขียวปลอม** แต่เกตที่แดงด้วยเหตุที่อ่านไม่ออกคือเกตที่คนจะเลิกเชื่อ
#
# เลขใบของไฟล์ migration **ก่อนกติกา task 083** ที่หัวไฟล์ยังอ้างใบงานด้วยพาธ — แก้ไม่ได้
# เพราะ apply ไปแล้ว (checksum) ⇒ ยกเว้นจากด่าน "พาธเน่า" แต่ยังนับเป็นของที่ต้องมีตัวตนจริง
# 🔴 **ว่างคือสภาพที่ถูกต้องของรายการนี้ในรีโปนี้** (darin ใบ 001) — ที่ groove-clinic มันคือ
# รายชื่อ migration ที่เกิด *ก่อน* กติกาห้ามอ้างพาธใบงาน และแก้ไม่ได้แล้วเพราะ apply ไปแล้ว
# · ที่นี่ยังไม่มีไฟล์ migration สักใบ (schema ขึ้นด้วย `prisma db push`) ⇒ ไม่มีของที่แช่แข็ง
# ⚠️ **ห้ามเติมเลขล่วงหน้า** — แถวที่ไม่มีไฟล์รองรับคือสุสานที่ด่านข้างล่างนี้แดงใส่พอดี
FROZEN_TASK_PATH_MIGRATIONS=""

frozen_seen=""
# 🔴 **สามฟิลด์ ไม่ใช่การตัดสตริง** (ใบ 314) — `git grep` เปล่า ๆ quote ชื่อไฟล์ที่ไม่ใช่ ASCII
# ⇒ ข้อความ FAIL เอ่ยพาธที่ก๊อปไปใช้ไม่ได้ · และ `case "$f" in prisma/migrations/*)` ไม่แมตช์
# ⇒ หัว migration ชื่อไทยจะถูกตัดสินด้วยแขนที่ผิด = แดงที่แก้ไม่ได้ (prisma checksum)
# · `-z` ทำให้ระเบียนเป็น `พาธ<NUL>เลขบรรทัด<NUL>เนื้อ<ขึ้นบรรทัดใหม่>` (วัดแล้ว git 2.53.0)
# ⇒ `read` ทีละฟิลด์ ซึ่งแก้อีกเรื่องให้ฟรีด้วย: ชื่อไฟล์ที่มี `:` เคยเลื่อนทุกฟิลด์
# ⚠️ `--no-column` กลายเป็นของจำเป็นเหตุที่สอง — ถ้ามีคอลัมน์ จะมีฟิลด์ NUL ที่สี่
while IFS= read -r -d '' f && IFS= read -r -d '' ln && IFS= read -r p; do
  [ -n "$f" ] || continue

  case "$f" in
    prisma/migrations/*)
      # ไม่ถามว่าพาธชี้ถูกไหม (ซ่อมไม่ได้) — ถามว่า **ไฟล์นี้มีสิทธิ์มีพาธไหม** (กติกา 083)
      n="$(basename "$f")"; n="${n%%_*}"
      case " $FROZEN_TASK_PATH_MIGRATIONS " in
        *" $n "*) frozen_seen="$frozen_seen $n" ;;
        *)
          echo "FAIL: $f:$ln — หัว migration อ้างใบงานด้วย**พาธ**: $p"
          echo "      กติกา task 083: ต้องอ้างด้วย **เลขใบ** (\`ใบงาน task NNN\`) ไม่ใช่พาธ —"
          echo "      ไฟล์ที่ apply แล้วแก้ไม่ได้ (prisma เก็บ checksum ไว้ใน _prisma_migrations) ⇒ พาธที่เน่าแล้วเน่าถาวร"
          fail=1
          ;;
      esac
      continue
      ;;
  esac

  [ -e "$p" ] && continue
  slug="${p##*/}"
  home=""
  for d in todo todo-human done; do
    [ -e "tasks/$d/$slug" ] && { home="tasks/$d/$slug"; break; }
  done
  if [ -n "$home" ]; then
    echo "FAIL: $f:$ln — พาธใบงานชี้ผิดบ้าน: $p"
    echo "      บ้านจริงวันนี้: $home"
  else
    # คนละใบกับข้างบนโดยตั้งใจ: อันบนแก้ด้วยการสลับพาธ อันนี้แก้ไม่ได้โดยไม่มีคนตัดสิน
    echo "FAIL: $f:$ln — พาธใบงานชี้ไฟล์ที่ไม่มีในสามบ้าน: $p"
    echo "      (slug เปลี่ยนชื่อ หรือใบถูกยุบ — ต้องตัดสินด้วยคนว่าพอยน์เตอร์นี้ควรชี้ไปไหน)"
  fi
  fail=1
done < <(git grep -z --untracked -I --no-color --no-column -noE \
  'tasks/(todo|todo-human|done)/[0-9]{3}-[a-z0-9-]+\.md' \
