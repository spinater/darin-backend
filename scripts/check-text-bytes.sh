# ── ตัวช่วยชี้ตำแหน่งไบต์ที่ผิด (เดินเฉพาะทาง FAIL ⇒ ราคาไม่ลงไปอยู่ในรอบปกติ)
#
# ⚠️ **ห้ามใช้ `| head -1` หรือ `awk … exit`** — ท่อที่ปิดก่อนต้นทางเขียนจบทำให้ต้นทางได้ SIGPIPE
# แล้ว `pipefail` คืน 141 ⇒ FAIL ปลอมกลางเกต ซึ่งเป็นกับดักที่ §7 บันทึกไว้เองจากใบ 095
# ⇒ `awk` ที่นี่อ่านจนจบสตรีมเสมอ
nul_count() { # $1 = พาธ ; stdout = จำนวนไบต์ NUL
  local total nonul
  total=$(wc -c < "$1")
  nonul=$(LC_ALL=C tr -d '\000' < "$1" | wc -c)
  echo $((total - nonul))
}

nul_first_offset() { # $1 = พาธ ; stdout = ออฟเซ็ตนับจาก 0 ของ NUL ตัวแรก (ไม่มี = -1)
  # 🔴 **ต้องย้ายขึ้นบรรทัดใหม่ของเดิมออกไปก่อน** — `tr '\000' '\n'` เฉย ๆ ทำให้ NUL กลายเป็น
  # ขึ้นบรรทัดใหม่ที่แยกไม่ออกจากของเดิม ⇒ `NR==1` คือบรรทัดแรกของ *ไฟล์* ไม่ใช่ไบต์ก่อน NUL
  # (เคส B ของ selftest จับได้จริงตอนเขียน: ไฟล์สามบรรทัด NUL อยู่บรรทัด 3 แต่ได้ออฟเซ็ต 5)
  # ⇒ สลับสองอย่างในจังหวะเดียว: `\n` → `\001` และ `\000` → `\n`
  # `LC_ALL=C` ที่นี่คุม `length()` ให้นับ **ไบต์** ไม่ใช่อักขระ — ไฟล์รีโปนี้เป็นไทยเกือบทั้งใบ
  # ⚠️ **ต่อท้ายด้วยไบต์ยาม** — ถ้า NUL เป็น *ไบต์สุดท้าย* ของไฟล์ สตรีมจะจบด้วย `\n` พอดี
  # ⇒ awk เห็นเรคคอร์ดเดียว ⇒ คืน `-1` ซึ่งเป็นค่าที่ฟังก์ชันนี้นิยามเองว่า "ไม่มี NUL"
  # แล้วผู้เรียกเอา -1 ไปเข้า `head -c` ⇒ ข้อความบอกออฟเซ็ตติดลบบนบรรทัดที่เพิ่งบอกว่ามี NUL
  # (รีวิวของใบ 277 จับได้ · เคส V ของ selftest เฝ้าไว้)
  { LC_ALL=C tr '\n\000' '\001\n' < "$1"; printf 'x'; } |
    LC_ALL=C awk 'NR==1 { n = length($0) } END { print (NR > 1 ? n : -1) }'
}

nul_first_line() { # $1 = พาธ ; $2 = ออฟเซ็ตนับจาก 0 ; stdout = เลขบรรทัด
  local before
  # `--` ไม่ใช่ของประดับ: ไฟล์ชื่อขึ้นต้นด้วยขีดที่รากรีโปทำให้ `head` อ่านชื่อเป็นธง
  before=$(head -c "$2" -- "$1" | LC_ALL=C wc -l)
  echo $((before + 1))
}

