    # ⇒ `[` อ่านไม่ออกแล้วแดงด้วยข้อความที่ไม่เกี่ยวกับเรื่องที่ตรวจ ⇒ บีบเหลือบรรทัดเดียวเสมอ
    # ⚠️ ไฟล์นี้รันใต้ `set -e` ⇒ `grep` ที่ไม่เจออะไร (exit 1) จะ **ฆ่าสคริปต์เงียบ ๆ**
