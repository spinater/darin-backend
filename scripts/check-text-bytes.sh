      fail=1
      ;;
  esac
  # เทียบเป็นสตริงตรง ๆ ห้าม `case` (ใบ 190) — แถวอาจมีอักขระที่ `case` อ่านเป็น glob
  # 🔑 **แต่ต้องเทียบด้วยกติกาเดียวกับที่ `kind_declared` ใช้จับคู่** — แถวนามสกุลจับคู่แบบ
  # *ไม่สนตัวพิมพ์* ⇒ `PDF` ข้าง `pdf` คือแถวซ้ำจริง · เทียบตรงตัวพิมพ์จะปล่อยผ่าน แล้วไป
  # โผล่เป็นข้อความด่านสุสาน "ไม่มีไฟล์ชนิดนี้ในรีโปแล้ว" ที่เป็นเท็จตามตัวอักษร (รีวิวใบ 277)
