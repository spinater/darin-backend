  fi
fi

declare -a KIND_MATCHED_ROWS=()
kind_declared() { # $1 = พาธ ; return 0 = มีแถวประกาศไว้ · ผลข้างเคียง: `KIND_MATCHED_ROWS`
  local p="$1" base ext i v
  KIND_MATCHED_ROWS=()
  base="${p##*/}"
  case "$base" in
    ?*.*) ext="${base##*.}" ;;
    *) ext="" ;;   # `.gitkeep` `Dockerfile` ⇒ ไม่มีนามสกุล
  esac
  ext="${ext,,}"
  for i in "${!kind_row_val[@]}"; do
    v="${kind_row_val[$i]}"
    case "$v" in
      */*) [ "$p" = "$v" ] || continue ;;
      *)
        [ -n "$ext" ] || continue
        [ "$ext" = "${v,,}" ] || continue
        ;;
    esac
    # 🔑 **จดทุกแถวที่แมตช์ ไม่ใช่แถวแรกแล้วออก** — ไม่งั้นแถวรูปพาธที่ถูกแถวนามสกุลบังไว้
    # จะไม่เคยถูกมาร์ก แล้วไปโดนด่านสุสานด้วยข้อความ "ไม่มีไฟล์ชนิดนี้ในรีโปแล้ว" ทั้งที่ไฟล์
    # อยู่ตรงนั้น ⇒ FAIL ที่บอกสาเหตุผิด ซึ่งแพงกว่าไม่มี FAIL (รีวิวใบ 277 · เคส X)
    kind_hit["$v"]=1
    KIND_MATCHED_ROWS+=("$v")
  done
  [ "${#KIND_MATCHED_ROWS[@]}" -gt 0 ]
}

# ── การกวาด: ทุกไฟล์ที่ git ถือ (รวมของที่ยังไม่ `git add` ผ่านธง `-o`) ลบของที่ `.gitignore` กิน
while IFS= read -r -d '' f; do
  if [ -L "$f" ]; then links=$((links + 1)); continue; fi
  [ -f "$f" ] || continue
  if [ ! -s "$f" ]; then
    # 🔑 ไฟล์ว่างก็ทำให้ `grep -Iq .` ตอบ "ไม่แมตช์" เหมือนไฟล์ binary — แต่ 0 ไบต์ไม่มีไบต์ให้ผิด
    # ⇒ แดงใส่มันคือแดงปลอมที่แก้ไม่ได้ · ของจริงในรีโปนี้: web/public/.gitkeep
    empty=$((empty + 1))
    continue
  fi
  if kind_declared "$f"; then
    declared=$((declared + 1))
    # 🔴 **ทิศที่สองของด่านกันสุสาน** (รีวิวใบ 277) — ทิศแรกถามแค่ "แถวนี้ถูกใช้ไหม" ซึ่งเป็น
    # คำถามที่ **แถวกว้างเกินตอบผ่านเสมอ**: เติมแถว `rs` หนึ่งแถว แล้วไฟล์ `.rs` ทั้ง 725 ใบ
    # หลุดจากคลังทันที โดยแถวนั้นถูกมาร์กว่า "ใช้แล้ว" และ selftest ยังเขียว 67/67 (วัดแล้ว)
    # ⇒ ต้องถามคำถามที่สอง: **ของที่แถวนี้ข้ามไป เป็น binary จริงไหม** · เจอไฟล์ text แม้ใบเดียว
    # = แถวนั้นไม่ใช่ "ชนิดที่ตั้งใจให้เป็น binary" แต่เป็นตัวปิดตา ⇒ FAIL เรียกชื่อทั้งแถวและไฟล์
    if ! flen_is_binary "$f"; then
      for v in ${KIND_MATCHED_ROWS[@]+"${KIND_MATCHED_ROWS[@]}"}; do
        [ -n "${kind_text[$v]+x}" ] || kind_text["$v"]="$f"
      done
    fi
    continue
  fi
  swept=$((swept + 1))
  # `grep` ที่อ่านไฟล์ไม่ได้ก็คืน non-zero เหมือนกัน ⇒ `flen_is_binary` ตอบ "binary" ให้ไฟล์ที่
  # แค่ถูก `chmod 000` หรือหายไประหว่างลูป ⇒ เกตจะสั่งให้ไปแก้ไบต์ของไฟล์ที่ไม่มีไบต์ผิดเลย
  # ⇒ แยกสาเหตุออกมาก่อน คนละข้อความ คนละทางแก้ (รีวิวใบ 277 · เคส W)
  if [ ! -r "$f" ]; then
    echo "FAIL: $f — อ่านไฟล์ไม่ได้ (สิทธิ์? หายไประหว่างรอบ?) ⇒ ตัดสินไบต์ของมันไม่ได้"
    echo "      (นี่คนละเรื่องกับไบต์ควบคุมดิบ — แก้สิทธิ์ไฟล์ ไม่ใช่แก้เนื้อไฟล์)"
    fail=1
    continue
  fi
  flen_is_binary "$f" || continue
  n=$(nul_count "$f")
  if [ "$n" -gt 0 ]; then
    off=$(nul_first_offset "$f")
    ln=$(nul_first_line "$f" "$off")
    echo "FAIL: $f — ตั้งใจให้เป็น text แต่ไบต์บอกว่า binary · NUL $n ไบต์ ตัวแรกที่บรรทัด $ln (ออฟเซ็ต $off)"
    echo '      เขียนแทนไบต์ดิบด้วยรูปที่อ่านออก — ใน TS/JS ใช้ escape \u0000 (ค่าสตริงเท่าเดิมทุกบิต)'
    echo '      ในร้อยแก้ว/.md เขียนตัวอักษรหกตัว \u0000 ลงไปตรง ๆ (การ์ดใบ 210 กับ 277 ทำแบบนี้)'
  else
    echo "FAIL: $f — ตั้งใจให้เป็น text แต่ไบต์บอกว่า binary · ไม่พบ NUL ⇒ เป็นไบต์ที่ไม่ใช่ข้อความในเนื้อไฟล์"
    echo "      (ถ้าไฟล์นี้ตั้งใจให้เป็น binary จริง ที่ของมันคือแถวใน $KINDS_FILE)"
  fi
  echo "      ระหว่างที่ยังเป็นแบบนี้ ไฟล์นี้อยู่นอกสายตาของ check-file-length.sh และ check-card-paths.sh"
  fail=1
done < <(git ls-files -c -o --exclude-standard -z | LC_ALL=C sort -z -u)

# ── ตัวข้ามห้ามเป็นสุสาน — แถวที่ไม่มีไฟล์ชนิดนั้นเหลือแล้ว คือตัวข้ามที่กว้างเกินของจริง
for i in "${!kind_row_val[@]}"; do
  v="${kind_row_val[$i]}"
  [ -n "${kind_hit[$v]+x}" ] && continue
  echo "FAIL: $KINDS_FILE:${kind_row_no[$i]} — ไม่มีไฟล์ชนิดนี้ในรีโปแล้ว: $v (ถอดแถวออก — ตัวข้ามห้ามเป็นสุสาน)"
  echo "      (ตัวข้ามที่กว้างกว่าของที่มีอยู่จริง คือพื้นที่ที่ด่านนี้มองไม่เห็น โดยไม่มีใครเห็นแถวด้วย)"
  fail=1
done

# ── ทิศที่สอง: แถวที่ข้ามไฟล์ซึ่งไบต์เป็น text = แถวที่กว้างเกินชนิดที่มันอ้างว่าเป็น
for i in "${!kind_row_val[@]}"; do
  v="${kind_row_val[$i]}"
  [ -n "${kind_text[$v]+x}" ] || continue
  echo "FAIL: $KINDS_FILE:${kind_row_no[$i]} — แถว \"$v\" ข้ามไฟล์ที่ไบต์เป็น text อยู่: ${kind_text[$v]}"
  echo "      (แถวนี้ประกาศว่า \"ชนิดนี้ตั้งใจให้เป็น binary\" แต่ของที่มันข้ามไม่ใช่ ⇒ มันคือตัวปิดตา"
  echo "       ไม่ใช่ตัวข้าม · ถ้ามีไฟล์ binary จริงแค่ไม่กี่ใบ ให้ใช้แถวรูป **พาธ** แทนรูปนามสกุล)"
  fail=1
done

# ── `swept = 0` = FAIL (บทเรียนใบ 193) — ตัวเลือกไฟล์ที่ว่างเปล่าไม่ส่งเสียงใด ๆ ด้วยตัวมันเอง
if [ "$swept" -eq 0 ]; then
  echo "FAIL: check-text-bytes กวาดไป 0 ไฟล์ — ตัวเลือกไฟล์พังหรือ cwd ผิด (ไม่ใช่ 'ไม่มีอะไรผิด')"
  fail=1
fi

if [ "$fail" -eq 0 ]; then
  echo "check-text-bytes: OK — กวาด $swept ไฟล์ · ประกาศ binary $declared ใบ · ว่าง $empty ใบ · symlink $links ใบ"
fi
exit "$fail"
