    fence==1 && seen && /^[[:space:]]*-[[:space:]]/ { n++ }
    END { print n+0 }
  ' "$card")
  if [ "${#sources[@]}" -ne "$declared" ]; then
    echo "FAIL: $card — frontmatter ประกาศ $declared รายการ แต่อ่านเป็น source ได้ ${#sources[@]} (หาย $((declared - ${#sources[@]}))) — ตัวอ่าน sources: หยุดก่อนจบรายการ (task 149)"
    fail=1
    card_bad=1
  fi

  [ "${#sources[@]}" -eq 0 ] && { [ "$card_bad" -eq 1 ] && bad_cards=$((bad_cards + 1)); continue; }

  ct=$(ftime "$card")
  for s in "${sources[@]}"; do
    if [ ! -e "$s" ]; then
      echo "FAIL: $card — source does not exist: $s"
      fail=1
      card_bad=1
      continue
    fi
    st=$(ftime "$s")
    if [ "$st" -gt "$ct" ]; then
      echo "STALE: $card — source newer than card: $s (update the card in the same commit)"
      fail=1
      card_bad=1
    fi
  done
  [ "$card_bad" -eq 1 ] && bad_cards=$((bad_cards + 1))
done < <(find .docs/knowledge -type f -name '*.md' | LC_ALL=C sort)

