# committer time of a path; INF if untracked or dirty; 0 if it has no commits yet but is clean-staged
#
# task 095: `git` ที่ **ล้มเหลว** (ไม่ใช่ "ไม่มีคอมมิต") ต้องไม่ถูกอ่านว่าเวลา 0 — เวลา 0
# แปลว่า "source เก่ากว่าการ์ดเสมอ" ⇒ ทุกการ์ดดูสดหมด ⇒ เกตเขียวโดยไม่ได้เทียบอะไรเลย
# (คลาสเดียวกับ FAIL ปลอมของ check-sql-coverage แต่โกหกไปทาง PASS)
ftime() {
  local p="$1" out rc=0
  if [ -n "$(git status --porcelain -- "$p")" ]; then
    echo "$INF"
    return
  fi
  out="$(git log -1 --format=%ct -- "$p")" || rc=$?
  if [ "$rc" -ne 0 ]; then
    echo "check-knowledge: FAIL — git log อ่าน $p ไม่สำเร็จ (exit $rc) — ปัญหาการอ่าน input ไม่ใช่การ์ดเก่า" >&2
    exit 1
  fi
  # ว่าง = ไฟล์ยังไม่มีคอมมิต (staged/ใหม่เอี่ยม) ซึ่งเป็นสถานะปกติ ไม่ใช่ความล้มเหลว
  [ -n "$out" ] && echo "$out" || echo 0
}

